"""
Train GPT2-medium with DPO (Direct Preference Optimization) to reduce toxicity.

Uses pairwise dataset of toxic/nontoxic continuations generated by PPLM.
DPO hyperparameters from Table 8:
- Learning rate: 1e-6
- Batch size: 4
- Optimizer: RMSProp
- Gradient accumulation steps: 1
- Max gradient norm: 10
- Validation metric: loss/valid
- Validation patience: 10
- DPO beta: 0.1
"""

import argparse
import os
import json
import copy
import numpy as np
import torch
import torch.nn.functional as F
from torch.utils.data import DataLoader, Dataset
from transformers import GPT2LMHeadModel, GPT2Tokenizer
from tqdm import tqdm


class PairwiseDataset(Dataset):
    """Dataset of (prompt, chosen, rejected) triples for DPO."""
    
    def __init__(self, pairs, tokenizer, max_length=256):
        self.pairs = pairs
        self.tokenizer = tokenizer
        self.max_length = max_length
    
    def __len__(self):
        return len(self.pairs)
    
    def __getitem__(self, idx):
        pair = self.pairs[idx]
        return pair["prompt"], pair["chosen"], pair["rejected"]


def tokenize_pair(prompt, chosen, rejected, tokenizer, max_length=256):
    """Tokenize a (prompt, chosen, rejected) triple."""
    # Tokenize prompt + chosen
    pos_text = prompt + chosen
    neg_text = prompt + rejected
    
    pos_enc = tokenizer(
        pos_text,
        truncation=True,
        max_length=max_length,
        return_tensors="pt"
    )
    neg_enc = tokenizer(
        neg_text,
        truncation=True,
        max_length=max_length,
        return_tensors="pt"
    )
    prompt_enc = tokenizer(
        prompt,
        truncation=True,
        max_length=max_length,
        return_tensors="pt"
    )
    
    return {
        "pos_input_ids": pos_enc["input_ids"].squeeze(0),
        "pos_attention_mask": pos_enc["attention_mask"].squeeze(0),
        "neg_input_ids": neg_enc["input_ids"].squeeze(0),
        "neg_attention_mask": neg_enc["attention_mask"].squeeze(0),
        "prompt_len": prompt_enc["input_ids"].shape[1]
    }


def collate_dpo(batch, tokenizer, max_length=256):
    """Collate function for DPO training."""
    prompts, chosens, rejecteds = zip(*batch)
    
    tokenized = [
        tokenize_pair(p, c, r, tokenizer, max_length)
        for p, c, r in zip(prompts, chosens, rejecteds)
    ]
    
    # Pad sequences
    max_pos_len = max(t["pos_input_ids"].shape[0] for t in tokenized)
    max_neg_len = max(t["neg_input_ids"].shape[0] for t in tokenized)
    
    pos_ids = torch.zeros(len(tokenized), max_pos_len, dtype=torch.long)
    pos_mask = torch.zeros(len(tokenized), max_pos_len, dtype=torch.long)
    neg_ids = torch.zeros(len(tokenized), max_neg_len, dtype=torch.long)
    neg_mask = torch.zeros(len(tokenized), max_neg_len, dtype=torch.long)
    prompt_lens = []
    
    for i, t in enumerate(tokenized):
        pos_len = t["pos_input_ids"].shape[0]
        neg_len = t["neg_input_ids"].shape[0]
        pos_ids[i, :pos_len] = t["pos_input_ids"]
        pos_mask[i, :pos_len] = t["pos_attention_mask"]
        neg_ids[i, :neg_len] = t["neg_input_ids"]
        neg_mask[i, :neg_len] = t["neg_attention_mask"]
        prompt_lens.append(t["prompt_len"])
    
    return {
        "pos_input_ids": pos_ids,
        "pos_attention_mask": pos_mask,
        "neg_input_ids": neg_ids,
        "neg_attention_mask": neg_mask,
        "prompt_lens": torch.tensor(prompt_lens)
    }


def compute_log_probs(model, input_ids, attention_mask, prompt_len):
    """
    Compute log probabilities of the continuation (after prompt).
    
    Args:
        model: language model
        input_ids: [batch, seq_len]
        attention_mask: [batch, seq_len]
        prompt_len: scalar, length of prompt
    
    Returns:
        log_probs: [batch] sum of log probs over continuation tokens
    """
    outputs = model(input_ids=input_ids, attention_mask=attention_mask)
    logits = outputs.logits  # [batch, seq_len, vocab_size]
    
    # Shift for next-token prediction
    shift_logits = logits[:, :-1, :]  # [batch, seq_len-1, vocab_size]
    shift_labels = input_ids[:, 1:]   # [batch, seq_len-1]
    shift_mask = attention_mask[:, 1:]  # [batch, seq_len-1]
    
    # Compute log probs
    log_probs = F.log_softmax(shift_logits, dim=-1)
    token_log_probs = log_probs.gather(-1, shift_labels.unsqueeze(-1)).squeeze(-1)
    # [batch, seq_len-1]
    
    # Mask out prompt tokens (only count continuation)
    # prompt_len is the length of the prompt; continuation starts at prompt_len
    # In shifted version, continuation starts at prompt_len - 1
    batch_size, seq_len = shift_labels.shape
    continuation_mask = torch.zeros_like(shift_mask, dtype=torch.float)
    for i in range(batch_size):
        start = max(0, prompt_len[i].item() - 1)
        continuation_mask[i, start:] = shift_mask[i, start:].float()
    
    # Sum log probs over continuation
    sum_log_probs = (token_log_probs * continuation_mask).sum(dim=-1)  # [batch]
    return sum_log_probs


def dpo_loss(
    policy_pos_logprobs,
    policy_neg_logprobs,
    ref_pos_logprobs,
    ref_neg_logprobs,
    beta=0.1
):
    """
    DPO loss:
    L_DPO = -E[log sigma(beta * log P - beta * log N)]
    where P = pi_theta(y+|w) / pi_ref(y+|w)
          N = pi_theta(y-|w) / pi_ref(y-|w)
    """
    log_P = policy_pos_logprobs - ref_pos_logprobs
    log_N = policy_neg_logprobs - ref_neg_logprobs
    
    loss = -F.logsigmoid(beta * (log_P - log_N)).mean()
    return loss


def train_dpo(args):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Using device: {device}")

    # Load tokenizer and models
    print("Loading GPT2-medium...")
    tokenizer = GPT2Tokenizer.from_pretrained("gpt2-medium")
    tokenizer.pad_token = tokenizer.eos_token
    
    # Policy model (to be trained)
    policy_model = GPT2LMHeadModel.from_pretrained("gpt2-medium").to(device)
    
    # Reference model (frozen)
    ref_model = GPT2LMHeadModel.from_pretrained("gpt2-medium").to(device)
    ref_model.eval()
    for param in ref_model.parameters():
        param.requires_grad_(False)

    # Load dataset
    print("Loading dataset...")
    with open(args.train_data, "r") as f:
        train_pairs = json.load(f)
    with open(args.val_data, "r") as f:
        val_pairs = json.load(f)
    
    print(f"Train pairs: {len(train_pairs)}, Val pairs: {len(val_pairs)}")

    train_dataset = PairwiseDataset(train_pairs, tokenizer, args.max_length)
    val_dataset = PairwiseDataset(val_pairs, tokenizer, args.max_length)

    train_loader = DataLoader(
        train_dataset,
        batch_size=args.batch_size,
        shuffle=True,
        collate_fn=lambda b: collate_dpo(b, tokenizer, args.max_length)
    )
    val_loader = DataLoader(
        val_dataset,
        batch_size=args.batch_size,
        shuffle=False,
        collate_fn=lambda b: collate_dpo(b, tokenizer, args.max_length)
    )

    # Optimizer: RMSProp (from Table 8)
    optimizer = torch.optim.RMSprop(
        policy_model.parameters(),
        lr=args.lr
    )

    os.makedirs(args.output_dir, exist_ok=True)
    
    best_val_loss = float("inf")
    patience_counter = 0
    
    for epoch in range(args.max_epochs):
        policy_model.train()
        total_loss = 0.0
        num_batches = 0
        
        for batch in tqdm(train_loader, desc=f"Epoch {epoch+1}"):
            pos_ids = batch["pos_input_ids"].to(device)
            pos_mask = batch["pos_attention_mask"].to(device)
            neg_ids = batch["neg_input_ids"].to(device)
            neg_mask = batch["neg_attention_mask"].to(device)
            prompt_lens = batch["prompt_lens"].to(device)
            
            # Compute policy log probs
            policy_pos_lp = compute_log_probs(policy_model, pos_ids, pos_mask, prompt_lens)
            policy_neg_lp = compute_log_probs(policy_model, neg_ids, neg_mask, prompt_lens)
            
            # Compute reference log probs
            with torch.no_grad():
                ref_pos_lp = compute_log_probs(ref_model, pos_ids, pos_mask, prompt_lens)
                ref_neg_lp = compute_log_probs(ref_model, neg_ids, neg_mask, prompt_lens)
            
            # DPO loss
            loss = dpo_loss(
                policy_pos_lp, policy_neg_lp,
                ref_pos_lp, ref_neg_lp,
                beta=args.beta
            )
            
            optimizer.zero_grad()
            loss.backward()
            
            # Gradient clipping (max norm = 10, from Table 8)
            torch.nn.utils.clip_grad_norm_(policy_model.parameters(), args.max_grad_norm)
            
            optimizer.step()
            
            total_loss += loss.item()
            num_batches += 1
        
        avg_train_loss = total_loss / num_batches
        print(f"Epoch {epoch+1}: Train Loss = {avg_train_loss:.4f}")
        
        # Validation
        policy_model.eval()
        val_loss = 0.0
        val_batches = 0
        
        with torch.no_grad():
            for batch in tqdm(val_loader, desc="Validation"):
                pos_ids = batch["pos_input_ids"].to(device)
                pos_mask = batch["pos_attention_mask"].to(device)
                neg_ids = batch["neg_input_ids"].to(device)
                neg_mask = batch["neg_attention_mask"].to(device)
                prompt_lens = batch["prompt_lens"].to(device)
                
                policy_pos_lp = compute_log_probs(policy_model, pos_ids, pos_mask, prompt_lens)
                policy_neg_lp = compute_log_probs(policy_model, neg_ids, neg_mask, prompt_lens)
                ref_pos_lp = compute_log_probs(ref_model, pos_ids, pos_mask, prompt_lens)
                ref_neg_lp = compute_log_probs(ref_model, neg_ids, neg_mask, prompt_lens)
                
                loss = dpo_loss(
                    policy_pos_lp, policy_neg_lp,
                    ref_pos_lp, ref_neg_lp,
                    beta=args.beta
                )
                val_loss += loss.item()
                val_batches += 1
        
        avg_val_loss = val_loss / val_batches
        print(f"Epoch {epoch+1}: Val Loss = {avg_val_loss:.4f}")
        
        # Early stopping with patience
        if avg_val_loss < best_val_loss:
            best_val_loss = avg_val_loss
            patience_counter = 0
            # Save best model
            policy_model.save_pretrained(os.path.join(args.output_dir, "gpt2_dpo_best"))
            tokenizer.save_pretrained(os.path.join(args.output_dir, "gpt2_dpo_best"))
            print(f"Saved best model with val loss: {best_val_loss:.4f}")
        else:
            patience_counter += 1
            print(f"Patience: {patience_counter}/{args.patience}")
            if patience_counter >= args.patience:
                print("Early stopping triggered")
                break
    
    # Save final model
    policy_model.save_pretrained(os.path.join(args.output_dir, "gpt2_dpo_final"))
    tokenizer.save_pretrained(os.path.join(args.output_dir, "gpt2_dpo_final"))
    print(f"Training complete. Best val loss: {best_val_loss:.4f}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--train_data", type=str, default="data/pplm_pairs/train_pairs.json")
    parser.add_argument("--val_data", type=str, default="data/pplm_pairs/val_pairs.json")
    parser.add_argument("--output_dir", type=str, default="checkpoints/dpo")
    parser.add_argument("--max_length", type=int, default=256)
    # DPO hyperparameters from Table 8
    parser.add_argument("--lr", type=float, default=1e-6)
    parser.add_argument("--batch_size", type=int, default=4)
    parser.add_argument("--max_grad_norm", type=float, default=10.0)
    parser.add_argument("--beta", type=float, default=0.1)
    parser.add_argument("--patience", type=int, default=10)
    parser.add_argument("--max_epochs", type=int, default=100)
    args = parser.parse_args()
    train_dpo(args)
