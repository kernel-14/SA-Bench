import argparse
import json
import logging
import sys
import traceback
import os
import contextlib
import io
import importlib.util

# Configure logging to stderr to avoid interfering with stdout JSON output.
# This ensures that only the final JSON result appears on stdout.
logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s", stream=sys.stderr)
logger = logging.getLogger(__name__)


@contextlib.contextmanager
def suppress_stdout_stderr():
    """A context manager to suppress stdout and stderr of the executed code."""
    with open(os.devnull, 'w') as fnull:
        old_stdout = sys.stdout
        old_stderr = sys.stderr
        sys.stdout = fnull
        sys.stderr = fnull
        try:
            yield
        finally:
            sys.stdout = old_stdout
            sys.stderr = old_stderr


def run_code_tests(generated_code_path: str, test_cases_path: str) -> None:
    """
    Executes Python code from `generated_code_path` against test cases from
    `test_cases_path` within a sandboxed environment and prints the outcome
    as a JSON object to stdout.

    This script is intended to be run as a subprocess by the main application
    (e.g., by CodeRewardFunction). It isolates the execution environment,
    suppresses stdout/stderr of the executed code, and catches common errors
    like SyntaxError, AssertionError, and other runtime exceptions.

    Args:
        generated_code_path: The file path to the Python code generated by the LLM
                             (the solution to be tested).
        test_cases_path: The file path to the Python code containing test assertions
                         that will verify the generated code.
    """
    result = {"passed": False, "error_message": "Unknown error."}
    
    # Store current working directory to restore later if necessary
    original_cwd = os.getcwd()
    
    # Use a temporary directory for execution to prevent file system pollution
    # and to potentially simplify import paths for 'solution.py' if needed.
    # Note: For this script, we're exec'ing directly from paths, so CWD change might
    # not be strictly necessary, but good for potential future robustness.
    temp_exec_dir = None

    try:
        # Create a temporary directory for execution
        temp_exec_dir = os.path.dirname(generated_code_path) # Assume files are already in a temp dir
        if not os.path.exists(generated_code_path):
            raise FileNotFoundError(f"Generated code file not found: {generated_code_path}")
        if not os.path.exists(test_cases_path):
            raise FileNotFoundError(f"Test cases file not found: {test_cases_path}")

        # Read the content of the generated solution code and test cases.
        with open(generated_code_path, "r", encoding="utf-8") as f:
            generated_code = f.read()
        with open(test_cases_path, "r", encoding="utf-8") as f:
            test_cases_code = f.read()

        # Create a clean execution environment (global and local scope dictionaries).
        # We include common built-ins and modules that solutions or tests might expect.
        # For security, one might want to restrict 'sys', 'os' or mock certain functions.
        exec_globals = {
            "__builtins__": __builtins__,
            "sys": sys,
            "os": os,
            "io": io,
            "contextlib": contextlib,
            # Add other common modules if frequently needed by generated code or tests
            # e.g., "math": __import__("math"), "heapq": __import__("heapq")
            # This is to minimize potential 'ModuleNotFoundError' within exec.
        }
        exec_locals = exec_globals  # Use the same dictionary for simplicity

        # Suppress any stdout/stderr generated by the solution or test code.
        # This ensures the parent process only receives the JSON result.
        with suppress_stdout_stderr():
            # Step 1: Execute the generated solution code.
            # This defines functions, classes, etc., in `exec_globals`/`exec_locals`.
            try:
                # Compile first to catch SyntaxErrors explicitly and report them clearly.
                compiled_generated_code = compile(generated_code, generated_code_path, "exec")
                exec(compiled_generated_code, exec_globals, exec_locals)
            except SyntaxError as e:
                # Provide a more specific error message for SyntaxError.
                raise SyntaxError(
                    f"Syntax error in generated code: {e.msg} (Line {e.lineno}, Col {e.offset})"
                ) from e
            except Exception as e:
                # Catch any other exceptions during the definition phase of the generated code.
                raise RuntimeError(
                    f"Error when defining generated code: {type(e).__name__}: {e}\n{traceback.format_exc()}"
                ) from e

            # Step 2: Execute the test cases.
            # These tests should call functions/classes defined in Step 1.
            try:
                # Compile first to catch SyntaxErrors in test cases.
                compiled_test_cases_code = compile(test_cases_code, test_cases_path, "exec")
                exec(compiled_test_cases_code, exec_globals, exec_locals)
                result["passed"] = True  # If no exception, all tests passed.
                result["error_message"] = ""  # Clear any previous error message.
            except AssertionError as e:
                # Specific error for failed assertions.
                result["error_message"] = f"AssertionError: {e}"
            except Exception as e:
                # Catch any other runtime exceptions during test execution.
                result["error_message"] = f"Runtime Error during tests: {type(e).__name__}: {e}\n{traceback.format_exc()}"

    except FileNotFoundError as e:
        result["error_message"] = f"File not found error: {e}"
    except SyntaxError as e:
        result["error_message"] = str(e)  # Already formatted in re-raise.
    except RuntimeError as e:
        result["error_message"] = str(e)
    except Exception as e:
        # Catch any unexpected errors in this script itself.
        result["error_message"] = f"Unexpected error in test runner: {type(e).__name__}: {e}\n{traceback.format_exc()}"
    finally:
        # Ensure current working directory is restored.
        if os.getcwd() != original_cwd:
            os.chdir(original_cwd)
        
        # Always print the final JSON result to stdout.
        # This is the primary way the calling process receives the result.
        print(json.dumps(result))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Execute Python code and run tests.")
    parser.add_argument(
        "--generated_code_path",
        type=str,
        required=True,
        help="Path to the file containing the generated Python code (solution)."
    )
    parser.add_argument(
        "--test_cases_path",
        type=str,
        required=True,
        help="Path to the file containing the Python test cases (assertions)."
    )
    # The timeout for the execution is typically managed by the parent process
    # using subprocess.run's `timeout` parameter. This script itself doesn't
    # implement a separate timer, but executes synchronously.
    args = parser.parse_args()

    run_code_tests(args.generated_code_path, args.test_cases_path)
