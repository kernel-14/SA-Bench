import re
from typing import Dict, Union, Any, List, Optional, Callable

import numpy as np
import torch
from datasets import Dataset
from scipy.stats import pearsonr
from sklearn.metrics import accuracy_score, matthews_corrcoef
from transformers import PreTrainedTokenizer, Trainer, TrainingArguments

from config import Config # Assuming config.py is in the same directory
from lora_sb import LoRASBModel # Import the custom LoRA-SB model
from dataset_utils import DatasetLoader # For data collator, and to infer model type


class Evaluator:
    """
    Evaluates the performance of a fine-tuned LoRA-SB model on various tasks.
    """

    def __init__(self, tokenizer: PreTrainedTokenizer, config: Config):
        """
        Initializes the Evaluator.

        Args:
            tokenizer (PreTrainedTokenizer): The tokenizer used for text decoding.
            config (Config): The global configuration object.
        """
        self._tokenizer = tokenizer
        self._config = config
        
        # Determine model type based on task name
        # This inference logic should align with dataset_utils.py's model type determination.
        if self._config.task_name in ["MetaMathQA", "COMMONSENSE170K"]:
            self._model_type = "causal_lm"
        elif self._config.task_name.startswith("glue_"):
            self._model_type = "sequence_classification"
        else:
            raise ValueError(f"Unknown task type for evaluation: {self._config.task_name}")

        print(f"Evaluator initialized for model type: {self._model_type}")

    def _parse_generated_answer(self, generated_text: str, task_name: str) -> Optional[Union[str, float, int]]:
        """
        Extracts the canonical answer from a model's generated text for generative tasks.

        Args:
            generated_text (str): The full text generated by the model.
            task_name (str): The name of the task to determine parsing logic.

        Returns:
            Union[str, float, int]: The extracted answer in a comparable format, or None if not found.
        """
        # For MetaMathQA (or general math problems like GSM8K, MATH)
        # Assumes generated text contains "Answer: <number>" or the last number is the answer.
        if task_name == "MetaMathQA":
            # Look for explicit "Answer: " pattern first
            match_explicit = re.search(r"Answer:\s*([-+]?\d*\.?\d+)", generated_text, re.IGNORECASE)
            if match_explicit:
                try:
                    num_str = match_explicit.group(1)
                    return float(num_str) if '.' in num_str else int(num_str)
                except ValueError:
                    return None
            
            # If not found, try to find the last numerical value in the text
            match_last_num = re.findall(r"[-+]?\d*\.\d+|\d+", generated_text)
            if match_last_num:
                try:
                    num_str = match_last_num[-1]
                    return float(num_str) if '.' in num_str else int(num_str)
                except ValueError:
                    return None
            return None
        
        # For COMMONSENSE170K (multiple-choice QA)
        # Assumes the model generates something like "Answer: A" or " (A)" for the chosen option.
        elif task_name == "COMMONSENSE170K":
            # Pattern to capture single capital letter after "Answer:" or within parentheses
            match = re.search(r"Answer:\s*([A-Za-z])|\(([A-Za-z])\)", generated_text, re.IGNORECASE)
            if match:
                # Group 1 for "Answer: A", Group 2 for "(A)". Convert to uppercase.
                return match.group(1).upper() if match.group(1) else match.group(2).upper()
            return None
        
        # Default behavior for other generative tasks or if no specific parsing applies
        return generated_text.strip() # Return the stripped generated text

    def _compute_metrics_for_task(self, task_name: str, predictions: np.ndarray, references: np.ndarray) -> Dict[str, float]:
        """
        Computes the appropriate metric(s) based on the specific task_name.

        Args:
            task_name (str): The specific task identifier (e.g., 'cola', 'boolq').
            predictions (np.ndarray): The model's processed predictions (e.g., class IDs, scores, extracted answers).
            references (np.ndarray): The ground truth labels or answers.

        Returns:
            Dict[str, float]: A dictionary containing the computed metric(s).
        """
        metrics: Dict[str, float] = {}

        if task_name == "MetaMathQA":
            # For numerical comparison, need to handle potential parsing failures (None)
            # Ensure both predictions and references are numerical or comparable
            valid_pairs = [(p, r) for p, r in zip(predictions, references) if p is not None and r is not None]
            if not valid_pairs:
                metrics["accuracy"] = 0.0
            else:
                # Convert to float for comparison as math answers can be floats
                # Note: `accuracy_score` expects exact matches. Floating point comparisons
                # might need tolerance for real-world scenarios, but exact is fine for benchmarks.
                metrics["accuracy"] = accuracy_score([float(p) for p, _ in valid_pairs], [float(r) for _, r in valid_pairs])
        
        elif task_name == "COMMONSENSE170K":
            # For multiple choice, predictions could be 'A', 'B' etc. and references could be 0, 1 etc.
            # Need to map integer references (0, 1, 2, 3...) to 'A', 'B', 'C', 'D' for comparison.
            # Assuming references are integer indices.
            char_references = np.array([chr(ord('A') + int(ref)) if isinstance(ref, (int, np.integer)) else ref for ref in references])
            valid_pairs = [(p, r) for p, r in zip(predictions, char_references) if p is not None and r is not None]

            if not valid_pairs:
                metrics["accuracy"] = 0.0
            else:
                metrics["accuracy"] = accuracy_score([p for p, _ in valid_pairs], [r for _, r in valid_pairs])

        # GLUE tasks (using specific sub-tasks from the dataset loader)
        elif task_name.startswith("glue_"):
            actual_task_name = task_name.split("_")[1]

            if actual_task_name == "cola":
                metrics["mcc"] = matthews_corrcoef(references, predictions)
            elif actual_task_name in ["rte", "mrpc", "qnli", "sst2"]:
                metrics["accuracy"] = accuracy_score(references, predictions)
            elif actual_task_name == "stsb":
                # Pearson correlation expects 1D arrays of scores
                pearson, _ = pearsonr(references, predictions)
                metrics["pearson"] = pearson
            else:
                print(f"Warning: No specific metrics defined for GLUE sub-task: {actual_task_name}. Falling back to accuracy.")
                metrics["accuracy"] = accuracy_score(references, predictions)
        else:
            # Fallback for any other task not explicitly defined
            print(f"Warning: No specific metrics defined for task: {task_name}. Falling back to accuracy.")
            metrics["accuracy"] = accuracy_score(references, predictions)

        return metrics

    def evaluate(self, model: LoRASBModel, eval_dataset: Dataset, task_name: str) -> Dict[str, float]:
        """
        Performs evaluation on a given dataset using the provided model and computes metrics.

        Args:
            model (LoRASBModel): The fine-tuned LoRA-SB model.
            eval_dataset (Dataset): The dataset split for evaluation (e.g., validation or test set).
                                    For generative tasks, this dataset is expected to contain an 'original_labels'
                                    column with the true answers in a comparable format.
            task_name (str): The specific name of the task being evaluated.

        Returns:
            Dict[str, float]: A dictionary of computed metrics.
        """
        model.eval() # Set model to evaluation mode

        # Prepare TrainingArguments for prediction
        training_args = TrainingArguments(
            output_dir=self._config.output_dir,
            per_device_eval_batch_size=self._config.evaluation_batch_size,
            dataloader_drop_last=False, # Don't drop last batch for evaluation
            # Minimal required args for prediction/generation with Trainer
            do_train=False, do_eval=True, do_predict=True,
            seed=self._config.random_seed,
            report_to="none", # Disable reporting to external services
            no_cuda=not torch.cuda.is_available(), # Disable CUDA if not available
            log_level="critical" # Suppress excessive logging from Trainer during evaluation
        )

        # Create a DataLoader for the eval_dataset to use with Trainer.generate or Trainer.predict
        data_collator = DatasetLoader(self._tokenizer, self._config).get_data_collator(
            task_name, self._model_type
        )

        # Instantiate a Trainer for evaluation
        trainer = Trainer(
            model=model,
            args=training_args,
            tokenizer=self._tokenizer,
            data_collator=data_collator,
        )

        predictions_for_metric: np.ndarray
        references_for_metric: np.ndarray

        if self._model_type == "causal_lm":
            # For generative tasks, use model.generate to get actual text outputs
            print("Performing text generation for evaluation...")
            
            # The 'input_ids' from the eval_dataset are needed for generation.
            # `Trainer.generate` expects a DataLoader or directly iterable dataset of input_ids.
            # The `trainer.predict` method does not call `model.generate` by default.
            # We need to explicitly call `model.generate` with the input IDs.

            # We assume eval_dataset's 'input_ids' are the prompts for generation.
            # And 'original_labels' contains the ground truth for comparison.
            if "original_labels" not in eval_dataset.column_names:
                raise ValueError("For causal_lm evaluation, 'eval_dataset' must contain an 'original_labels' column with ground truth answers.")
            
            # Extract input_ids for generation
            eval_input_ids = eval_dataset["input_ids"]
            
            # Explicitly move input_ids to model's device
            input_ids_on_device = [torch.tensor(ids).to(model.device) for ids in eval_input_ids]

            all_generated_tokens: List[List[int]] = []
            
            # Manual batching for generation if Trainer.generate is not flexible enough
            # Or use Trainer.predict with a custom decode function if possible
            # For now, let's use a simple loop. Trainer.generate has issues with Dataset inputs sometimes.
            
            # The following is a simplified loop. For actual batching with `model.generate`,
            # we would need to pass a DataLoader. Let's use `trainer.model.generate` directly.
            # `trainer.generate` typically takes a `test_dataset` but its internal handling
            # might not pass prompts correctly to `model.generate`.
            # A more robust way is to make sure eval_dataset for generate has only input_ids.
            
            # For simplicity, we'll iterate with small batches for generation.
            # This is less efficient than true batch generation but directly shows the logic.
            generated_texts: List[str] = []
            for i in range(0, len(eval_dataset), self._config.evaluation_batch_size):
                batch_input_ids = torch.stack(input_ids_on_device[i : i + self._config.evaluation_batch_size])
                
                # Assume original input is just prompt, model generates answer
                # Need to handle specific tokenizer behavior (e.g., Llama adds </s>)
                generation_output = trainer.model.generate(
                    input_ids=batch_input_ids,
                    max_new_tokens=self._config.max_seq_len // 2, # Generate up to half the max_seq_len for answers
                    num_beams=1, # Greedy decoding for simplicity, can be changed
                    do_sample=False, # No sampling for consistent evaluation
                    pad_token_id=self._tokenizer.pad_token_id,
                    attention_mask=torch.ones_like(batch_input_ids, device=model.device) # Explicit attention mask
                )
                
                # Decode only the newly generated tokens (after input_ids length)
                for j, output_ids in enumerate(generation_output):
                    prompt_len = batch_input_ids[j].shape[0]
                    generated_text = self._tokenizer.decode(output_ids[prompt_len:], skip_special_tokens=True)
                    generated_texts.append(generated_text.strip())

            parsed_predictions = np.array([self._parse_generated_answer(text, task_name) for text in generated_texts])
            
            predictions_for_metric = parsed_predictions
            references_for_metric = np.array(eval_dataset["original_labels"]) # Use the original ground truth answers
            
        else: # sequence_classification model type
            prediction_output = trainer.predict(eval_dataset)
            raw_predictions = prediction_output.predictions # These are logits
            references_for_metric = prediction_output.label_ids # These are integer class labels

            # For classification, convert logits to predicted class IDs
            if raw_predictions.ndim > 1 and raw_predictions.shape[1] > 1: # Multi-class classification
                predictions_for_metric = np.argmax(raw_predictions, axis=-1)
            else: # Binary classification (single logit) or regression (single score, e.g., STS-B)
                if task_name.split("_")[1] == "stsb": # Regression task
                    predictions_for_metric = raw_predictions # STS-B scores are already 1D
                else: # Binary classification, e.g., single logit output
                    # Assuming a threshold of 0 for binary classification logits (or 0.5 for probabilities)
                    predictions_for_metric = (raw_predictions > 0).astype(int) 

        # Compute metrics based on processed predictions and references
        computed_metrics = self._compute_metrics_for_task(task_name, predictions_for_metric, references_for_metric)
        print(f"Evaluation results for {task_name}: {computed_metrics}")
        return computed_metrics

