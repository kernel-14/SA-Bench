    def _text_to_symbolic(self, text_level: List[str], environment: str = "Sokoban") -> np.ndarray:
        """
        Converts a list of strings representing a level into its symbolic NumPy array format.

        Args:
            text_level (List[str]): A list of strings, where each string is a row of the grid.
            environment (str): "Sokoban" or "Mini PacMan" to determine grid size and channel count.

        Returns:
            np.ndarray: The (grid_h, grid_w, num_channels) symbolic NumPy array.
        
        Raises:
            ValueError: If an unsupported environment is provided.
        """
        if environment == "Sokoban":
            grid_h: int = self.sokoban_grid_size[0]
            grid_w: int = self.sokoban_grid_size[1]
            num_channels: int = self.sokoban_num_channels
        # elif environment == "Mini PacMan":
        #    grid_h, grid_w = self.config.get('environment.mini_pacman.grid_size', [13, 13])
        #    num_channels = self.config.get('environment.mini_pacman.observation_channels', 14)
        else:
            raise ValueError(f"Unsupported environment for _text_to_symbolic: {environment}")

        symbolic_grid: np.ndarray = np.zeros((grid_h, grid_w, num_channels), dtype=np.uint8)
        
        for r_idx, row_str in enumerate(text_level):
            if r_idx >= grid_h:
                break # Ignore extra rows if present
            for c_idx, char in enumerate(row_str):
                if c_idx >= grid_w:
                    break # Ignore extra columns if present
                symbolic_grid[r_idx, c_idx] = self._char_to_one_hot(char, environment)
        return symbolic_grid


    def _load_boxoban_levels(self, path: str) -> List[np.ndarray]:
        """
        Loads levels from a text file in Boxoban format. Each level is separated by two newlines.
        Levels are cached after the first load.

        Args:
            path (str): The file path to the Boxoban levels, relative to 'paths.data_dir'.

        Returns:
            List[np.ndarray]: A list of symbolic NumPy arrays, each representing a level.
        """
        full_path: str = os.path.join(self.config.get('paths.data_dir', 'data'), path)

        if full_path in self.level_cache:
            return self.level_cache[full_path]

        levels: List[np.ndarray] = []
        current_level_lines: List[str] = []
        
        if not os.path.exists(full_path):
            print(f"Warning: Boxoban level file not found at {full_path}. Returning empty list.")
            return []

        try:
            with open(full_path, 'r') as f:
                for line in f:
                    line = line.strip('\n') # Keep empty lines for separator check
                    if line == '': # Delimiter for levels
                        if current_level_lines:
                            levels.append(self._text_to_symbolic(current_level_lines))
                            current_level_lines = []
                    else:
                        current_level_lines.append(line)
                # Add the last level if file doesn't end with two newlines
                if current_level_lines:
                    levels.append(self._text_to_symbolic(current_level_lines))
            self.level_cache[full_path] = levels # Cache with full path
        except Exception as e:
            print(f"Error loading Boxoban levels from {full_path}: {e}. Returning empty list.")
            return []
        return levels


