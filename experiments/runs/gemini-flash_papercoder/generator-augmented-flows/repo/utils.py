# utils.py

import torch
import math
from typing import List, Tuple

class Utils:
    """
    Utility class containing various static methods for noise scheduling,
    loss weighting, timestep sampling, and progressive timestep adjustment.
    """

    @staticmethod
    def get_karras_sigmas(
        sigma_min: float,
        sigma_max: float,
        rho: float,
        N: int,
        device: torch.device
    ) -> torch.Tensor:
        """
        Generates a noise schedule according to the formulation proposed by Karras et al. (2022).
        The schedule defines N+1 noise levels from sigma_min to sigma_max.

        Args:
            sigma_min (float): The smallest noise level (sigma_0).
            sigma_max (float): The largest noise level (sigma_T).
            rho (float): A parameter controlling the distribution of noise levels.
            N (int): The total number of intermediate timesteps. The resulting
                     tensor will have N+1 sigma values, indexed from 0 to N.
            device (torch.device): The device (CPU or GPU) on which the tensor should be allocated.

        Returns:
            torch.Tensor: A tensor of shape (N + 1,) containing the calculated sigma_i values.
        """
        # Create a tensor of indices from 0 to N
        i_steps = torch.arange(N + 1, device=device, dtype=torch.float32)

        # Calculate the base term for the interpolation
        # sigma_0^(1/rho) + (i/N) * (sigma_T^(1/rho) - sigma_0^(1/rho))
        base_term = sigma_min**(1/rho) + \
                    (i_steps / N) * (sigma_max**(1/rho) - sigma_min**(1/rho))

        # Compute the sigma_i values by raising the base term to the power of rho
        sigmas = base_term**rho

        return sigmas

    @staticmethod
    def get_loss_weights(sigmas: torch.Tensor) -> torch.Tensor:
        """
        Calculates the weighting factor lambda(sigma_i) for each timestep's loss,
        emphasizing consistency at lower noise levels.

        Args:
            sigmas (torch.Tensor): A tensor of N+1 noise levels, as generated by get_karras_sigmas.

        Returns:
            torch.Tensor: A tensor of shape (N,) containing the loss weights lambda(sigma_i)
                          for i in {0, ..., N-1}.
        """
        # The formula is lambda(sigma_i) = 1 / (sigma_{i+1} - sigma_i).
        # For N+1 sigma values, there will be N loss weights.
        
        # Calculate the differences between consecutive sigma values
        # sigmas[1:] covers sigma_1 to sigma_N
        # sigmas[:-1] covers sigma_0 to sigma_{N-1}
        diffs = sigmas[1:] - sigmas[:-1]

        # Compute the reciprocal of these differences
        # Using torch.where to handle potential division by zero if diffs are extremely small,
        # although with Karras schedule, diffs should be positive.
        # Adding a small epsilon for numerical stability.
        epsilon = 1e-6
        weights = 1.0 / (diffs + epsilon)

        return weights

    @staticmethod
    def get_timestep_probabilities(
        sigmas: torch.Tensor,
        p_mean: float,
        p_std: float,
        device: torch.device
    ) -> torch.Tensor:
        """
        Computes the probabilities for sampling specific timesteps i (from 0 to N-1)
        during training, using an erf-based distribution.

        Args:
            sigmas (torch.Tensor): A tensor of N+1 noise levels.
            p_mean (float): Mean parameter for the erf function's argument.
            p_std (float): Standard deviation parameter for the erf function's argument.
            device (torch.device): The device on which the tensor should be allocated.

        Returns:
            torch.Tensor: A tensor of shape (N,) containing the normalized sampling
                          probabilities for each timestep index.
        """
        # The probabilities are calculated for sampling an index i from {0, ..., N-1},
        # corresponding to the interval [sigma_i, sigma_{i+1}]. Thus, there will be N probabilities.

        # Extract log(sigma_i) and log(sigma_{i+1}) for all i
        log_sigmas_i = torch.log(sigmas[:-1])
        log_sigmas_i_plus_1 = torch.log(sigmas[1:])

        # Compute the arguments for the erf function
        sqrt_2_p_std = math.sqrt(2.0) * p_std
        arg_i = (log_sigmas_i - p_mean) / sqrt_2_p_std
        arg_i_plus_1 = (log_sigmas_i_plus_1 - p_mean) / sqrt_2_p_std

        # Apply torch.erf()
        erf_i = torch.erf(arg_i)
        erf_i_plus_1 = torch.erf(arg_i_plus_1)

        # Calculate the raw probabilities
        raw_probs = erf_i_plus_1 - erf_i
        
        # Ensure probabilities are non-negative, and normalize them to sum to 1.
        # Using clamp(min=0.0) for robustness.
        normalized_probs = torch.clamp(raw_probs, min=0.0)
        
        # Handle cases where all raw_probs might be zero or sum to zero
        sum_probs = normalized_probs.sum()
        if sum_probs > 1e-6: # Check if sum_probs is not close to zero
            normalized_probs = normalized_probs / sum_probs
        else:
            # If all probabilities are very small or zero, assign uniform probability.
            # This is a fallback for numerical stability, though unlikely with typical params.
            print("Warning: Timestep probabilities sum to zero. Assigning uniform probabilities.")
            normalized_probs = torch.ones_like(normalized_probs) / normalized_probs.numel()


        return normalized_probs

    @staticmethod
    def get_progressive_N(
        current_step: int,
        total_steps: int,
        s0: int,
        s1: int
    ) -> int:
        """
        Dynamically adjusts the number of timesteps N during training, starting from a small
        number and progressively increasing it up to a maximum, based on the current training step.

        Args:
            current_step (int): The current training iteration (k).
            total_steps (int): The total number of training steps (K).
            s0 (int): The initial number of timesteps.
            s1 (int): The final (maximum) number of timesteps.

        Returns:
            int: The current number of timesteps N(k).
        """
        if s0 == s1:
            # If initial and final steps are the same, N remains constant.
            # The formula N(k) = min(s0 * 2^exponent, s1) + 1 will correctly return s0 + 1
            # if exponent is 0 and s0 <= s1.
            return s0 + 1

        # Calculate K' = floor(K / (log2(s1/s0) + 1))
        # Add a small epsilon to s1/s0 in log2 argument to prevent log(0) if s0 is very large.
        log2_ratio = math.log2(s1 / s0)
        K_prime = math.floor(total_steps / (log2_ratio + 1.0))

        # Ensure K_prime is at least 1 to prevent division by zero in the next step
        K_prime = max(1, K_prime)

        # Calculate the exponent: floor(k / K')
        exponent = math.floor(current_step / K_prime)

        # Compute the initial guess for N: s0 * (2^exponent)
        N_val = s0 * (2**exponent)

        # Take the minimum with s1
        N_val = min(N_val, s1)

        # Finally, add 1 to N_val to account for sigma_0 up to sigma_N (N+1 points, N intervals)
        N_k = N_val + 1

        return N_k

