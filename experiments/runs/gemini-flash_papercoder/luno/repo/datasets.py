class PdeDatasetLoader(abc.ABC):
    """
    Abstract Base Class for PDE data loading and generation.
    Defines a standardized interface for different PDE sources.
    """

    def __init__(self, config: Config):
        """
        Initializes the base loader with a Config object.

        Args:
            config: An instance of the Config class containing all experiment parameters.
        """
        self.config = config
        self.data_dir = Path(config.results_dir) / "datasets" / config.pde_name
        self.data_dir.mkdir(parents=True, exist_ok=True)

    @abc.abstractmethod
    def generate_data(
        self, num_trajectories: int, is_ood: bool = False, ood_type: str = "Base"
    ) -> Tuple[jnp.ndarray, jnp.ndarray, jnp.ndarray]:
        """
        Generates new PDE simulation data and prepares it for FNO input/output.

        Args:
            num_trajectories: The total number of trajectories to generate.
            is_ood: Flag indicating if OOD data generation logic should be applied.
            ood_type: Specifies the type of OOD scenario (e.g., 'Base', 'Flip').

        Returns:
            A tuple (inputs, targets, initial_conditions).
            - inputs: FNO input array. Shape varies by PDE (1D/2D) and padding.
                      (num_traj, initial_time_steps, *spatial_dims, total_input_channels)
            - targets: Ground truth next time step.
                       (num_traj, *spatial_dims, output_channels)
            - initial_conditions: The very first state of each trajectory.
                                  (num_traj, *spatial_dims, output_channels)
        """
        pass

    @abc.abstractmethod
    def load_data(
        self, split: str, ood_type: str = "Base"
    ) -> Tuple[jnp.ndarray, jnp.ndarray, jnp.ndarray]:
        """
        Loads existing, pre-generated PDE simulation data from disk.

        Args:
            split: A string indicating the dataset split to load ('train', 'val', 'test').
            ood_type: Specifies the OOD variant to load (defaults to 'Base').

        Returns:
            A tuple (inputs, targets, initial_conditions) as described in generate_data.
        """
        pass


class APEBenchDatasetLoader(PdeDatasetLoader):
    """
    Data loader for 1D PDE datasets generated by APEBench (e.g., Burgers', Hyper Diffusion).
    Simulates APEBench output as direct integration with APEBench is beyond current scope.
    """

    def __init__(self, config: Config):
        """
        Initializes the APEBenchDatasetLoader.

        Args:
            config: An instance of the Config class.
        """
        super().__init__(config)
        self.pde_name = config.pde_name
        self.spatial_res = config.spatial_res
        self.temporal_res = config.temporal_res
        self.initial_time_steps = config.initial_time_steps
        self.input_padding = config.input_padding
        self.output_channels = config.fno_output_channels

        # Spatial axes for 1D data for padding, (batch, time, x, y, channels) -> x is axis 2
        self.spatial_axes_for_padding = (2,)
        # In 1D, y-dimension is 1, so the original data might be (T, X) or (T, X, 1)
        # We target (batch, time, spatial_x, spatial_y, channels) for consistency
        # so spatial_y dimension will be 1.

    def _get_filepaths(self, split: str, ood_type: str = "Base") -> Dict[str, Path]:
        """Helper to get standardized file paths."""
        base_name = f"{self.pde_name}_1d_{split}"
        if ood_type != "Base":
            logging.warning(f"OOD type '{ood_type}' specified for 1D APEBench dataset. "
                            f"APEBench datasets are typically not OOD variants. Using '{base_name}' path.")
        paths = {
            "inputs": self.data_dir / f"{base_name}_inputs.npy",
            "targets": self.data_dir / f"{base_name}_targets.npy",
            "initial_conditions": self.data_dir / f"{base_name}_initial_conditions.npy",
        }
        return paths

    def generate_data(
        self, num_trajectories: int, is_ood: bool = False, ood_type: str = "Base"
    ) -> Tuple[jnp.ndarray, jnp.ndarray, jnp.ndarray]:
        """
        Simulates generation of APEBench 1D PDE data.
        In a real scenario, this would involve calling the APEBench API or scripts.

        Args:
            num_trajectories: Number of trajectories to generate.
            is_ood: Ignored for APEBench, as OOD is handled by 2D Advection-Diffusion.
            ood_type: Ignored for APEBench.

        Returns:
            Tuple of (inputs, targets, initial_conditions) as jax.numpy.ndarray.
        """
        logging.info(f"Simulating APEBench data generation for {self.pde_name} (1D) "
                     f"with {num_trajectories} trajectories...")

        all_inputs = []
        all_targets = []
        all_initial_conditions = []

        # Simulate APEBench output: (total_temporal_res, spatial_res)
        # APEBench returns 59 time steps, we use that directly.
        apebench_full_trajectory_len = self.temporal_res

        for _ in tqdm(range(num_trajectories), desc=f"Generating {self.pde_name} 1D data"):
            # Simulate a full trajectory (e.g., (time, spatial_x))
            # Data typically in range [-1, 1] for FNOs
            # For simplicity, let's use a random walk-like simulation in space and time
            initial_state = np.random.rand(self.spatial_res, 1) * 2 - 1 # (spatial_x, 1)
            full_trajectory_np = np.zeros(
                (apebench_full_trajectory_len, self.spatial_res, 1)
            )
            full_trajectory_np[0, :, :] = initial_state

            for t_step in range(1, apebench_full_trajectory_len):
                # Simple diffusion-like behavior: average of neighbors + some noise
                prev_state = full_trajectory_np[t_step - 1, :, 0]
                next_state_1d = (
                    0.5 * prev_state
                    + 0.25 * np.roll(prev_state, 1)
                    + 0.25 * np.roll(prev_state, -1)
                    + np.random.randn(self.spatial_res) * 0.05
                )
                full_trajectory_np[t_step, :, 0] = next_state_1d

            # Ensure data matches expected FNO input/output structure
            # (time, spatial_x, spatial_y=1, channels=1)
            full_trajectory_np = full_trajectory_np[:, :, np.newaxis, :] # Add spatial_y dim

            # Extract FNO inputs and targets
            # Inputs: (initial_time_steps, spatial_x, spatial_y, 1)
            fno_input_state = full_trajectory_np[
                              : self.initial_time_steps, :, :, :
                              ]

            # Targets: (spatial_x, spatial_y, 1) - next step after input
            fno_target = full_trajectory_np[
                         self.initial_time_steps, :, :, :
                         ]

            # Apply padding to the input state
            # input_state_padded: (initial_time_steps, padded_spatial_x, padded_spatial_y=1, 1)
            # spatial_axes_for_padding = (1,) if fno_input_state is (time, x, y, channels)
            # but since fno_input_state here is (time, x, 1, channels), spatial_x is axis 1
            # and spatial_y is axis 2.
            padded_fno_input_state = pad_input(
                jnp.asarray(fno_input_state), self.input_padding, self.spatial_axes_for_padding
            )

            # APEBench 1D data usually doesn't have velocity/reaction as separate conditions
            # For consistency, we use stack_conditions. It will just return the state if others are None.
            # The 'channel' for 1D FNO is 1 for the state.
            # (initial_time_steps, padded_spatial_x, padded_spatial_y, 1)
            final_fno_input = stack_conditions(padded_fno_input_state)

            all_inputs.append(final_fno_input)
            all_targets.append(jnp.asarray(fno_target))
            all_initial_conditions.append(jnp.asarray(full_trajectory_np[0, :, :, :])) # First time step

        # Stack all collected data
        stacked_inputs = jnp.stack(all_inputs)
        stacked_targets = jnp.stack(all_targets)
        stacked_initial_conditions = jnp.stack(all_initial_conditions)

        # Save data
        split_name = "train" if num_trajectories == self.config.num_train_traj else \
            ("val" if num_trajectories == self.config.num_val_traj else "test")
        paths = self._get_filepaths(split_name)
        np.save(paths["inputs"], stacked_inputs)
        np.save(paths["targets"], stacked_targets)
        np.save(paths["initial_conditions"], stacked_initial_conditions)
        logging.info(f"Generated and saved 1D {self.pde_name} {split_name} data to {self.data_dir}")

        return stacked_inputs, stacked_targets, stacked_initial_conditions

    def load_data(
        self, split: str, ood_type: str = "Base"
    ) -> Tuple[jnp.ndarray, jnp.ndarray, jnp.ndarray]:
        """
        Loads 1D PDE data from disk.

        Args:
            split: 'train', 'val', or 'test'.
            ood_type: Ignored for APEBench.

        Returns:
            Tuple of (inputs, targets, initial_conditions) as jax.numpy.ndarray.
        """
        paths = self._get_filepaths(split)
        if not paths["inputs"].exists():
            logging.error(f"Data for {self.pde_name} {split} (1D) not found at {paths['inputs']}. "
                          "Please generate data first.")
            raise FileNotFoundError(f"Data for {self.pde_name} {split} (1D) not found.")

        logging.info(f"Loading {self.pde_name} {split} (1D) data from {self.data_dir}...")
        inputs = jnp.asarray(np.load(paths["inputs"]))
        targets = jnp.asarray(np.load(paths["targets"]))
        initial_conditions = jnp.asarray(np.load(paths["initial_conditions"]))
        return inputs, targets, initial_conditions


class AdvectionDiffusionDatasetLoader(PdeDatasetLoader):
    """
    Data loader for 2D Advection-Diffusion-Reaction datasets,
    including Out-of-Distribution (OOD) variations, using a custom numerical solver.
    """

    def __init__(self, config: Config):
        """
        Initializes the AdvectionDiffusionDatasetLoader.

        Args:
            config: An instance of the Config class.
        """
        super().__init__(config)
        self.pde_name = config.pde_name
        self.spatial_res = config.spatial_res
        self.temporal_res = config.temporal_res # Subsampled temporal resolution (59)
        self.dt_solver = config.ood_dt_solver
        self.diffusion_coefficient = config.ood_diffusion_coefficient
        self.ood_variants = config.ood_variants
        self.initial_time_steps = config.initial_time_steps
        self.input_padding = config.input_padding
        self.output_channels = config.fno_output_channels

        self.solver_total_timesteps = 200 # As per paper, then subsampled to 59
        self.spatial_axes_for_padding = (2, 3) # (batch, time, x, y, channels) -> x is axis 2, y is axis 3

        # Create meshgrid for spatial operations
        self.x = np.linspace(0, 1, self.spatial_res, endpoint=False)
        self.y = np.linspace(0, 1, self.spatial_res, endpoint=False)
        self.X, self.Y = np.meshgrid(self.x, self.y)
        self.dx = self.x[1] - self.x[0]
        self.dy = self.y[1] - self.y[0]

    def _get_filepaths(self, split: str, ood_type: str) -> Dict[str, Path]:
        """Helper to get standardized file paths."""
        base_name = f"{self.pde_name}_2d_{split}_{ood_type}"
        paths = {
            "inputs": self.data_dir / f"{base_name}_inputs.npy",
            "targets": self.data_dir / f"{base_name}_targets.npy",
            "initial_conditions": self.data_dir / f"{base_name}_initial_conditions.npy",
        }
        return paths

    def _generate_gaussian_blob(self, x_grid: np.ndarray, y_grid: np.ndarray) -> np.ndarray:
        """Generates a single 2D Gaussian blob."""
        center_x = np.random.rand()
        center_y = np.random.rand()
        std_dev = 0.05 + np.random.rand() * 0.1 # Range from 0.05 to 0.15
        amplitude = 0.5 + np.random.rand() * 0.5 # Range from 0.5 to 1.0
        return amplitude * np.exp(
            -((x_grid - center_x) ** 2 + (y_grid - center_y) ** 2) / (2 * std_dev ** 2)
        )

    def _generate_triangular_source(self, x_grid: np.ndarray, y_grid: np.ndarray) -> np.ndarray:
        """Generates a randomly placed triangular heat source."""
        source = np.zeros_like(x_grid)
        center_x = np.random.rand()
        center_y = np.random.rand()
        width = 0.1 + np.random.rand() * 0.1 # Width of triangle base

        # Simple triangular shape based on distance from center
        dist = np.sqrt((x_grid - center_x)**2 + (y_grid - center_y)**2)
        source[dist < width] = 1.0 - (dist[dist < width] / width)
        return source * (0.1 + np.random.rand() * 0.1) # Amplitude scaling

    def _generate_cloud_sink(self, x_grid: np.ndarray, y_grid: np.ndarray) -> np.ndarray:
        """Generates a randomly placed cloud-shaped heat sink (multiple small Gaussians)."""
        sink = np.zeros_like(x_grid)
        num_small_blobs = np.random.randint(3, 7)
        for _ in range(num_small_blobs):
            sink -= self._generate_gaussian_blob(x_grid, y_grid) * (0.05 + np.random.rand() * 0.05)
        return sink


    def generate_data(
        self, num_trajectories: int, is_ood: bool = False, ood_type: str = "Base"
    ) -> Tuple[jnp.ndarray, jnp.ndarray, jnp.ndarray]:
        """
        Generates 2D Advection-Diffusion-Reaction data with specified OOD variations.

        Args:
            num_trajectories: Number of trajectories to generate.
            is_ood: If True, `ood_type` will be used to determine conditions.
            ood_type: Specifies the OOD variant ('Base', 'Flip', 'Pos', 'Pos-Neg', 'Pos-Neg-Flip').

        Returns:
            Tuple of (inputs, targets, initial_conditions) as jax.numpy.ndarray.
        """
        logging.info(f"Generating 2D Advection-Diffusion-Reaction data for OOD type: {ood_type} "
                     f"with {num_trajectories} trajectories...")

        all_inputs = []
        all_targets = []
        all_initial_conditions = []

        for _ in tqdm(range(num_trajectories), desc=f"Generating {ood_type} data"):
            # 1. Initial Condition: Random Gaussian blobs
            num_blobs = np.random.randint(1, 11)  # 1-10 Gaussian blobs
            initial_u = np.zeros_like(self.X)
            for _ in range(num_blobs):
                initial_u += self._generate_gaussian_blob(self.X, self.Y)
            initial_u = np.clip(initial_u, 0, 1) # Normalize to sensible range

            # 2. Velocity Field and Reaction Term based on ood_type
            vx, vy = (np.random.rand(2) * 2 - 1) * 0.1 # Random velocity components [-0.1, 0.1]
            velocity_field_x = np.full_like(self.X, vx)
            velocity_field_y = np.full_like(self.Y, vy)
            reaction_term = np.zeros_like(self.X)

            if ood_type in ["Flip", "Pos-Neg-Flip"]:
                # Reverse velocity field at the center (e.g., central 20% of domain)
                center_idx_x = int(self.spatial_res * 0.4)
                center_idx_y = int(self.spatial_res * 0.4)
                center_width_x = int(self.spatial_res * 0.2)
                center_width_y = int(self.spatial_res * 0.2)

                velocity_field_x[
                    center_idx_x : center_idx_x + center_width_x,
                    center_idx_y : center_idx_y + center_width_y,
                ] *= -1
                velocity_field_y[
                    center_idx_x : center_idx_x + center_width_x,
                    center_idx_y : center_idx_y + center_width_y,
                ] *= -1

            if ood_type in ["Pos", "Pos-Neg", "Pos-Neg-Flip"]:
                reaction_term += self._generate_triangular_source(self.X, self.Y)

            if ood_type in ["Pos-Neg", "Pos-Neg-Flip"]:
                reaction_term += self._generate_cloud_sink(self.X, self.Y)

            # Reshape for solver (spatial_res, spatial_res)
            # Reshape conditions for stacking: (spatial_res, spatial_res, 1) or (spatial_res, spatial_res, 2)
            velocity_field_np = np.stack([velocity_field_x, velocity_field_y], axis=-1) # (spatial_res, spatial_res, 2)
            reaction_term_np = reaction_term[:, :, np.newaxis] # (spatial_res, spatial_res, 1)

            # Combine conditions to be passed to FNO later
            input_conditions_for_fno = jnp.asarray(
                np.concatenate([velocity_field_np, reaction_term_np], axis=-1)
            ) # (spatial_res, spatial_res, 3)

            # 3. Solve PDE
            # initial_u should be (spatial_res, spatial_res) for the solver
            full_trajectory_solved = self._solve_pde(
                initial_u, velocity_field_np, reaction_term_np
            ) # (solver_total_timesteps, spatial_res, spatial_res)

            # Subsample time steps from solver output (200 -> 59)
            subsample_indices = np.linspace(0, self.solver_total_timesteps - 1,
                                            self.temporal_res, dtype=int)
            subsampled_trajectory = full_trajectory_solved[subsample_indices] # (temporal_res, spatial_res, spatial_res)

            # 4. Extract FNO Inputs/Targets
            # FNO input requires (initial_time_steps, spatial_x, spatial_y, 1) for the state
            fno_input_state_np = subsampled_trajectory[
                                 : self.initial_time_steps, :, :
                                 ][:, :, :, np.newaxis] # Add channel dim
            
            # Target is the next time step (spatial_x, spatial_y, 1)
            fno_target_np = subsampled_trajectory[
                            self.initial_time_steps, :, :
                            ][:, :, np.newaxis] # Add channel dim

            # Convert to jnp.ndarray
            fno_input_state = jnp.asarray(fno_input_state_np)
            fno_target = jnp.asarray(fno_target_np)
            initial_condition = jnp.asarray(subsampled_trajectory[0, :, :, np.newaxis])

            # 5. Apply padding to the input state
            padded_fno_input_state = pad_input(
                fno_input_state, self.input_padding, self.spatial_axes_for_padding
            )

            # 6. Glue Conditions: velocity_field_np and reaction_term_np are constant over time
            # They need to be expanded to match the time dimension of the state, then stacked.
            # Shape: (initial_time_steps, padded_spatial_x, padded_spatial_y, num_cond_channels)
            
            # The velocity and reaction term are effectively input conditions *for all* time steps
            # so they should have the same spatial dimensions as the state.
            # Pad input_conditions_for_fno spatially, then repeat across time steps
            padded_input_conditions_for_fno = pad_input(
                input_conditions_for_fno, self.input_padding, (0, 1) # spatial_x, spatial_y
            )
            
            # Now, expand padded_input_conditions_for_fno to have the time dimension
            # (initial_time_steps, padded_spatial_x, padded_spatial_y, num_cond_channels)
            expanded_conditions = jnp.tile(
                padded_input_conditions_for_fno[jnp.newaxis, :, :, :],
                (self.initial_time_steps, 1, 1, 1)
            )

            final_fno_input = stack_conditions(padded_fno_input_state, conditions=expanded_conditions)
            
            all_inputs.append(final_fno_input)
            all_targets.append(fno_target)
            all_initial_conditions.append(initial_condition)

        stacked_inputs = jnp.stack(all_inputs)
        stacked_targets = jnp.stack(all_targets)
        stacked_initial_conditions = jnp.stack(all_initial_conditions)

        # Save data
        split_name = "train" if num_trajectories == self.config.num_train_traj else \
            ("val" if num_trajectories == self.config.num_val_traj else "test")
        
        # OOD datasets for evaluation are always 'test' split. Training for OOD is always 'Base'
        if ood_type == "Base" and split_name == "train":
            # This is the training data for the base model
            paths = self._get_filepaths("train", ood_type)
        elif ood_type == "Base" and split_name == "val":
            # This is the validation data for the base model
            paths = self._get_filepaths("val", ood_type)
        else:
            # All other generated data are for test sets for specific OOD types
            paths = self._get_filepaths("test", ood_type)


        np.save(paths["inputs"], stacked_inputs)
        np.save(paths["targets"], stacked_targets)
        np.save(paths["initial_conditions"], stacked_initial_conditions)
        logging.info(f"Generated and saved 2D {self.pde_name} {ood_type} {split_name} data to {self.data_dir}")

        return stacked_inputs, stacked_targets, stacked_initial_conditions

    def load_data(
        self, split: str, ood_type: str = "Base"
    ) -> Tuple[jnp.ndarray, jnp.ndarray, jnp.ndarray]:
        """
        Loads 2D Advection-Diffusion-Reaction data from disk.

        Args:
            split: 'train', 'val', or 'test'.
            ood_type: Specifies the OOD variant ('Base', 'Flip', etc.).

        Returns:
            Tuple of (inputs, targets, initial_conditions) as jax.numpy.ndarray.
        """
        paths = self._get_filepaths(split, ood_type)
        if not paths["inputs"].exists():
            logging.error(f"Data for {self.pde_name} {split} {ood_type} (2D) not found at {paths['inputs']}. "
                          "Please generate data first.")
            raise FileNotFoundError(f"Data for {self.pde_name} {split} {ood_type} (2D) not found.")

        logging.info(f"Loading {self.pde_name} {split} {ood_type} (2D) data from {self.data_dir}...")
        inputs = jnp.asarray(np.load(paths["inputs"]))
        targets = jnp.asarray(np.load(paths["targets"]))
        initial_conditions = jnp.asarray(np.load(paths["initial_conditions"]))
        return inputs, targets, initial_conditions

    def _solve_pde(
        self,
        initial_condition: np.ndarray, # (H, W)
        velocity_field: np.ndarray,    # (H, W, 2) (vx, vy)
        reaction_term: np.ndarray,     # (H, W, 1) (R)
    ) -> np.ndarray:
        """
        Solves the 2D Advection-Diffusion-Reaction equation using RK4 and a 9-point stencil.
        The PDE is: du/dt + v.grad(u) = alpha * nabla^2 u + R
        or du/dt = -v.grad(u) + alpha * nabla^2 u + R

        Args:
            initial_condition: Initial state of the scalar field u (H, W).
            velocity_field: Velocity components (vx, vy) at each grid point (H, W, 2).
            reaction_term: Reaction term R at each grid point (H, W, 1).

        Returns:
            A numpy array of the full trajectory (solver_total_timesteps, H, W).
        """
        u = initial_condition.copy()
        H, W = self.spatial_res, self.spatial_res
        total_steps = self.solver_total_timesteps
        dt = self.dt_solver
        alpha = self.diffusion_coefficient

        trajectory = [u.copy()]

        def dudt_fn(u_current: np.ndarray, t: float, vx_field: np.ndarray, vy_field: np.ndarray, r_term: np.ndarray) -> np.ndarray:
            """
            Calculates the right-hand side of the PDE (du/dt).
            Uses 9-point stencil for Laplacian, central differences for advection gradients.
            Periodic boundary conditions are implicitly handled by np.roll.
            """
            # Extract velocity components
            vx = vx_field[:, :]
            vy = vy_field[:, :]
            r = r_term[:, :, 0] # Remove channel dim for R

            # 1. Central differences for gradients (dx, dy)
            # Using np.roll for periodic boundary conditions
            u_plus_dx = np.roll(u_current, shift=-1, axis=1) # u(i+1, j)
            u_minus_dx = np.roll(u_current, shift=1, axis=1)  # u(i-1, j)
            u_plus_dy = np.roll(u_current, shift=-1, axis=0) # u(i, j+1)
            u_minus_dy = np.roll(u_current, shift=1, axis=0)  # u(i, j-1)

            du_dx = (u_plus_dx - u_minus_dx) / (2 * self.dx)
            du_dy = (u_plus_dy - u_minus_dy) / (2 * self.dy)

            # Advection term: v.grad(u) = vx * du/dx + vy * du/dy
            advection_term = vx * du_dx + vy * du_dy

            # 2. Laplacian (2nd order central difference - 5 point stencil for simplicity of implementation)
            # The paper mentions "9-point stencil" but for Laplacian, a common 9-point stencil is a higher-order approx
            # or involves diagonals. A 5-point stencil is more standard for basic Laplacian.
            # (u(i+1,j) + u(i-1,j) + u(i,j+1) + u(i,j-1) - 4u(i,j)) / h^2
            # For 9-point, a common one uses diagonal neighbors too, but it's not universally defined.
            # I will use a simplified 5-point stencil for now, common for advection-diffusion.
            # If a specific 9-point Laplacian is intended, it should be explicitly defined.
            
            # Second derivatives
            d2u_dx2 = (u_plus_dx + u_minus_dx - 2 * u_current) / (self.dx ** 2)
            d2u_dy2 = (u_plus_dy + u_minus_dy - 2 * u_current) / (self.dy ** 2)
            
            # Diffusion term: alpha * nabla^2 u
            diffusion_term = alpha * (d2u_dx2 + d2u_dy2)

            # Combine all terms for du/dt
            # du/dt = -advection + diffusion + reaction
            return -advection_term + diffusion_term + r

        for t_idx in range(total_steps - 1):
            k1 = dudt_fn(u, t_idx * dt, velocity_field[:,:,0], velocity_field[:,:,1], reaction_term)
            k2 = dudt_fn(u + 0.5 * dt * k1, (t_idx + 0.5) * dt, velocity_field[:,:,0], velocity_field[:,:,1], reaction_term)
            k3 = dudt_fn(u + 0.5 * dt * k2, (t_idx + 0.5) * dt, velocity_field[:,:,0], velocity_field[:,:,1], reaction_term)
            k4 = dudt_fn(u + dt * k3, (t_idx + 1) * dt, velocity_field[:,:,0], velocity_field[:,:,1], reaction_term)

            u = u + (dt / 6) * (k1 + 2 * k2 + 2 * k3 + k4)
            trajectory.append(u.copy())

        return np.array(trajectory)

