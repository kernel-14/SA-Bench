# sampler.py
import numpy as np
import torch
from typing import Dict, Any, List, Tuple
from model import DiffusionModel  # Direct dependency on the DiffusionModel class for score function and processes


class Sampler:
    """
    Implements the sampling algorithm for score-based diffusion models as described in the paper.
    The sampler utilizes a randomized midpoint schedule to derive the trajectory of sampled data
    and process reverse diffusion with score functions.
    """

    def __init__(self, diffusion_model: DiffusionModel, config: Dict[str, Any]) -> None:
        """
        Initialize the Sampler class with a diffusion model and configuration parameters.

        Args:
            diffusion_model (DiffusionModel): The diffusion model providing score functions and processes.
            config (Dict[str, Any]): Configuration containing sampling hyperparameters.
        """
        self.diffusion_model = diffusion_model
        self.config = config

        # Extract sampling configuration
        sampling_config = config.get("sampling", {})
        self.T = sampling_config.get("T", 1000)  # Total number of steps
        self.K = sampling_config.get("K", 10)  # Number of rounds
        self.c0 = sampling_config.get("step_schedule", {}).get("c0", 0.001)  # Randomization constant c0
        self.c1 = sampling_config.get("step_schedule", {}).get("c1", 0.01)  # Randomization constant c1
        self.randomized = sampling_config.get("step_schedule", {}).get("randomized", True)

        # Validate configuration
        if self.T % self.K != 0:
            raise ValueError("T should be evenly divisible by K.")
        if self.c0 <= 0 or self.c1 <= 0:
            raise ValueError("Constants c0 and c1 must be positive.")

        self.N = self.T // self.K  # Number of steps per round
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")  # Enable GPU if available

    def sample(self) -> torch.Tensor:
        """
        Executes the sampling process using the randomized midpoint technique.

        Returns:
            torch.Tensor: Final sampled data resembling the target distribution.
        """
        # Step 1: Prepare the randomized time schedule
        tau_list = self.randomized_schedule(self.T, self.K, self.c0, self.c1)

        # Step 2: Initialize the sampling process
        dimensions = self.diffusion_model.dimensions
        Y_k = torch.randn((1, dimensions), device=self.device)  # Start with Gaussian noise (Y_0 ~ N(0, I_d))

        # Step 3: Start iterative sampling
        for k in range(self.K):
            tau_k_start = tau_list[k * self.N]
            tau_k_end = tau_list[(k + 1) * self.N - 1]

            Y_k = self._iterate_sampling(Y_k, tau_list, k, tau_k_start, tau_k_end)

        return Y_k

    def randomized_schedule(self, T: int, K: int, c0: float, c1: float) -> List[float]:
        """
        Generate a randomized time schedule for the sampling process.

        Args:
            T (int): Total number of diffusion steps.
            K (int): Number of rounds to divide into.
            c0 (float): Randomization parameter defining start of schedule.
            c1 (float): Randomization parameter adjusting step-length adaptation.

        Returns:
            List[float]: The interpolated schedule of time intervals.
        """
        time_steps = T + 1
        alpha_schedule = np.zeros(time_steps)
        alpha_schedule[T] = c0

        # Compute forward schedule
        for t in range(T - 1, -1, -1):
            alpha_schedule[t] = alpha_schedule[t + 1] + (c1 * alpha_schedule[t + 1] * (1 - alpha_schedule[t + 1]) * np.log(T)) / T

        tau_schedule = 1 - alpha_schedule  # Convert to tau values
        return tau_schedule.tolist()

    def _iterate_sampling(
        self, Y_k: torch.Tensor, tau_list: List[float], k: int, tau_k_start: float, tau_k_end: float
    ) -> torch.Tensor:
        """
        Perform one round of sampling (K iterations) using the randomized schedule.

        Args:
            Y_k (torch.Tensor): Current intermediate sample.
            tau_list (List[float]): The list of time steps generated by randomized_schedule().
            k (int): Current round index.
            tau_k_start (float): Start of the schedule for the current round.
            tau_k_end (float): End of the schedule for the current round.

        Returns:
            torch.Tensor: Updated sample after completing the round.
        """
        for n in range(self.N):
            tau_n_start = tau_list[k * self.N + n]
            tau_n_end = tau_list[k * self.N + n + 1] if (n + 1) < self.N else tau_k_end

            # Randomized midpoint approach: Choose tau uniformly between the interval.
            tau = torch.FloatTensor(1).uniform_(tau_n_start, tau_n_end).item()

            noise_factor = torch.sqrt(torch.tensor(1 - tau, device=self.device))
            variance_factor = torch.sqrt(torch.tensor(tau, device=self.device))

            # Score function evaluation
            s_tau = self.diffusion_model.score_function(Y_k, tau)

            # Update using randomized midpoint discretization
            Y_k = (Y_k / noise_factor) + (s_tau / ((1 - tau)**1.5)) * (tau_n_end - tau_n_start)

        # Noise injection at the end of the round (stochastic regularization)
        noise_injection = torch.sqrt(torch.tensor(tau_k_end - tau_k_start, device=self.device)) * torch.randn(
            Y_k.size(), device=self.device
        )
        Y_k = torch.sqrt((1 - tau_k_end) / (1 - tau_k_start)) * Y_k + noise_injection

        return Y_k
