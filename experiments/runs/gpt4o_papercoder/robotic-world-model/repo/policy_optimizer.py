# policy_optimizer.py

import torch
import torch.nn as nn
import torch.optim as optim
import numpy as np
from typing import List, Dict, Tuple
from rwm_model import RWMModel


class PolicyOptimizer:
    """
    The PolicyOptimizer class implements Model-Based Policy Optimization with Proximal Policy Optimization (MBPO-PPO)
    leveraging imagination rollouts generated by the Robotic World Model (RWM).
    """

    def __init__(self, model: RWMModel, config: dict, buffer: List[Tuple[torch.Tensor, torch.Tensor, float, torch.Tensor]]):
        """
        Initialize the PolicyOptimizer.

        Args:
            model (RWMModel): Trained Robotic World Model (RWM).
            config (dict): Configuration dictionary loaded from config.yaml.
            buffer (List[Tuple[torch.Tensor, torch.Tensor, float, torch.Tensor]]): Replay buffer to store environment and imagination transitions.
        """
        self.world_model = model
        self.config = config
        self.buffer = buffer

        # Extract training hyperparameters
        self.imagination_steps = self.config["policy_optimizer"]["imagination_steps"]
        self.discount_factor = self.config["policy_optimizer"]["discount_factor"]
        self.learning_rate = self.config["policy_optimizer"]["learning_rate"]
        self.ppo_epochs = self.config["policy_optimizer"]["ppo_epochs"]
        self.minibatches = self.config["policy_optimizer"]["ppo_minibatches"]
        self.clip_range = self.config["policy_optimizer"]["clip_range"]
        self.entropy_coeff = self.config["policy_optimizer"]["entropy_coeff"]
        self.kl_target = self.config["policy_optimizer"]["kl_target"]
        self.device = "cuda" if torch.cuda.is_available() else "cpu"

        # Initialize policy and value function networks
        self.policy = self._initialize_policy()
        self.value_function = self._initialize_value_function()

        # Optimizers
        self.policy_optimizer = optim.Adam(self.policy.parameters(), lr=self.learning_rate)
        self.value_optimizer = optim.Adam(self.value_function.parameters(), lr=self.learning_rate)

    def _initialize_policy(self) -> nn.Module:
        """Initialize the policy network as a three-layer MLP with ELU activations."""
        input_dim = self.config["model"]["input_dim"]
        output_dim = self.config["model"]["output_dim"]  # Same as action dimensions
        hidden_dim = 128

        return nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.ELU(),
            nn.Linear(hidden_dim, hidden_dim),
            nn.ELU(),
            nn.Linear(hidden_dim, output_dim),
            nn.Tanh()  # Output actions in [-1, 1] range
        ).to(self.device)

    def _initialize_value_function(self) -> nn.Module:
        """Initialize the value function network as a three-layer MLP with ELU activations."""
        input_dim = self.config["model"]["input_dim"]
        hidden_dim = 128

        return nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.ELU(),
            nn.Linear(hidden_dim, hidden_dim),
            nn.ELU(),
            nn.Linear(hidden_dim, 1)  # Output a scalar value
        ).to(self.device)

    def generate_rollouts(self) -> None:
        """
        Generate imagination-based rollouts using the trained RWM and store transitions in the replay buffer.
        """
        for _ in range(self.config["policy_optimizer"]["imagination_envs"]):
            # Sample initial observation from replay buffer
            initial_obs = np.random.choice(self.buffer)[0]  # Starting observation
            current_obs = initial_obs.to(self.device)  # Convert to device

            for step in range(self.imagination_steps):
                # Predict next observation and privileged info using the world model
                action = self.policy(current_obs).detach()  # Detach to avoid tracking gradients
                predicted_obs, _ = self.world_model(
                    history=current_obs.unsqueeze(0),  # Add batch dimension for RWM
                    actions=action.unsqueeze(0),
                )
                next_obs = predicted_obs.squeeze(0)  # Remove batch dimensions

                # Compute reward from the predicted observation
                reward = self._compute_reward(next_obs)

                # Append to replay buffer
                self.buffer.append((current_obs, action, reward, next_obs))

                # Update current observation
                current_obs = next_obs

    def _compute_reward(self, obs: torch.Tensor) -> float:
        """
        Compute the reward for a given observation as per the task reward function.

        Args:
            obs (torch.Tensor): Predicted observation from RWM.

        Returns:
            float: Computed reward.
        """
        # Example: Velocity tracking task reward
        velocity_command = obs[..., 9:12]  # Assuming velocity command index
        actual_velocity = obs[..., 0:3]   # Assuming actual velocity index
        reward = torch.exp(-torch.norm(velocity_command - actual_velocity, p=2)**2)
        return reward.item()

    def compute_ppo_loss(
        self,
        policy: nn.Module,
        value_function: nn.Module,
        trajectories: List[Tuple[torch.Tensor, torch.Tensor, float, torch.Tensor]],
    ) -> Tuple[torch.Tensor, torch.Tensor]:
        """
        Compute actor and critic loss for PPO updates.

        Args:
            policy (nn.Module): Policy network.
            value_function (nn.Module): Value function network.
            trajectories (List[Tuple[torch.Tensor, torch.Tensor, float, torch.Tensor]]): List of (state, action, reward, next_state) transitions.

        Returns:
            Tuple[torch.Tensor, torch.Tensor]: Actor loss and critic loss.
        """
        states, actions, rewards, next_states = zip(*trajectories)
        states = torch.stack(states).to(self.device)
        actions = torch.stack(actions).to(self.device)
        rewards = torch.tensor(rewards, dtype=torch.float32).to(self.device)
        next_states = torch.stack(next_states).to(self.device)

        # Compute returns and advantages
        with torch.no_grad():
            values = value_function(states).squeeze()  # Current state value
            next_values = value_function(next_states).squeeze()
            returns = rewards + self.discount_factor * next_values  # Bellman backup
            advantages = returns - values  # Advantage estimation

        # Compute policy ratios
        old_log_probs = torch.log_softmax(policy(states), dim=-1)
        new_log_probs = torch.log_softmax(policy(states), dim=-1)
        ratios = torch.exp(new_log_probs - old_log_probs)

        # Actor loss: Clipped surrogate objective
        actor_loss = -torch.min(
            ratios * advantages,
            torch.clamp(ratios, 1 - self.clip_range, 1 + self.clip_range) * advantages,
        ).mean()

        # Critic loss: Mean squared error between returns and value estimates
        critic_loss = nn.MSELoss()(value_function(states).squeeze(), returns)

        # Entropy loss for exploration
        entropy_loss = (-new_log_probs * torch.exp(new_log_probs)).mean()
        actor_loss -= self.entropy_coeff * entropy_loss

        return actor_loss, critic_loss

    def train_policy(self) -> None:
        """
        Train the policy and value function using the PPO algorithm.
        """
        for _ in range(self.ppo_epochs):
            # Sample trajectories from the replay buffer
            trajectories = [
                self.buffer[idx]
                for idx in np.random.choice(len(self.buffer), size=self.minibatches, replace=False)
            ]

            # Compute PPO losses
            actor_loss, critic_loss = self.compute_ppo_loss(self.policy, self.value_function, trajectories)

            # Update policy
            self.policy_optimizer.zero_grad()
            actor_loss.backward()
            self.policy_optimizer.step()

            # Update value function
            self.value_optimizer.zero_grad()
            critic_loss.backward()
            self.value_optimizer.step()

    def evaluate_policy(self) -> Dict[str, float]:
        """
        Evaluate the optimized policy on given evaluation metrics.

        Returns:
            Dict[str, float]: Dictionary of evaluation metrics (e.g., mean reward, KL divergence).
        """
        rewards = []
        kl_divergences = []

        for _ in range(self.minibatches):
            # Sample initial observation
            initial_obs = np.random.choice(self.buffer)[0].to(self.device)
            current_obs = initial_obs
            trajectory_rewards = []

            for step in range(self.imagination_steps):
                # Policy sample
                action = self.policy(current_obs).detach()
                predicted_obs, _ = self.world_model(
                    current_obs.unsqueeze(0), action.unsqueeze(0)
                )
                next_obs = predicted_obs.squeeze(0)

                # Reward and KL calculation
                reward = self._compute_reward(next_obs)
                trajectory_rewards.append(reward)

                kl_div = nn.KLDivLoss()(predicted_obs.log(), current_obs.exp())
                kl_divergences.append(kl_div.item())

                # Update state
                current_obs = next_obs

            rewards.append(np.mean(trajectory_rewards))

        return {"mean_reward": np.mean(rewards), "mean_kl_divergence": np.mean(kl_divergences)}
