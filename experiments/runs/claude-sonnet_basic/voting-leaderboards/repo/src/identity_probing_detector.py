def detect_model_from_response(
    response: str,
    target_model: str,
    keywords: Optional[list] = None,
) -> bool:
    """
    Detect if a response was generated by the target model using identity-probing.

    The classifier predicts the model as a positive match if the model's name
    or organization appears anywhere in the response (case-insensitive).

    Args:
        response: The model's response text
        target_model: The target model name to detect
        keywords: Optional list of keywords to search for. If None, uses MODEL_KEYWORDS.

    Returns:
        True if the response is predicted to be from the target model, False otherwise.
    """
    if keywords is None:
        keywords = MODEL_KEYWORDS.get(target_model, [])

    response_lower = response.lower()
    for keyword in keywords:
        if keyword.lower() in response_lower:
            return True
    return False


def evaluate_identity_probing_detector(
    responses: list,
    target_model: str,
    keywords: Optional[list] = None,
) -> float:
    """
    Evaluate the identity-probing detector on a list of responses.

    Args:
        responses: List of responses from the target model
        target_model: The target model name
        keywords: Optional list of keywords to search for

    Returns:
        Detection accuracy (fraction of responses correctly identified)
    """
    if not responses:
        return 0.0

    correct = sum(
        1 for r in responses if detect_model_from_response(r, target_model, keywords)
    )
    return correct / len(responses)


def run_identity_probing_experiment(
    model_responses: dict,
    target_model: str,
    prompts: Optional[list] = None,
    keywords: Optional[list] = None,
) -> dict:
    """
    Run the identity-probing experiment for a target model.

    Args:
        model_responses: Dictionary mapping prompt -> list of responses
        target_model: The target model name
        prompts: List of prompts to evaluate. If None, uses IDENTITY_PROBING_PROMPTS.
        keywords: Optional list of keywords to search for

    Returns:
        Dictionary with results per prompt, including accuracy
    """
    if prompts is None:
        prompts = IDENTITY_PROBING_PROMPTS

    if keywords is None:
        keywords = MODEL_KEYWORDS.get(target_model, [])

    results = {}
    for prompt in prompts:
        if prompt not in model_responses:
            logger.warning(f"Prompt '{prompt}' not found in model_responses")
            continue

        responses = model_responses[prompt]
        accuracy = evaluate_identity_probing_detector(responses, target_model, keywords)
        results[prompt] = {
            "accuracy": accuracy * 100,  # Convert to percentage
            "n_responses": len(responses),
            "n_correct": sum(
                1 for r in responses
                if detect_model_from_response(r, target_model, keywords)
            ),
        }
        logger.info(
            f"Model: {target_model}, Prompt: '{prompt[:50]}...', "
            f"Accuracy: {accuracy * 100:.1f}%"
        )

    return results


def get_best_identity_probing_prompt(results: dict) -> tuple:
    """
    Get the best identity-probing prompt based on detection accuracy.

    Args:
        results: Dictionary with results per prompt from run_identity_probing_experiment

    Returns:
        Tuple of (best_prompt, best_accuracy)
    """
    if not results:
        return None, 0.0

    best_prompt = max(results, key=lambda p: results[p]["accuracy"])
    return best_prompt, results[best_prompt]["accuracy"]
