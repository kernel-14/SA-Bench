"""
Identity-probing detector for de-anonymizing model responses.

This module implements the identity-probing attack described in Section 2.2 of the paper.
The attacker crafts prompts designed to elicit identifying information about the target model
(e.g., its name or organization).

The classifier predicts the model as a positive match if the model's name or organization
appears anywhere in the response.
"""

import re
