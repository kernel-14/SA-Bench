# Experiment 2 — Synthetic Heteroskedastic Data (Section 5.2)
# ---------------------------------------------------------------------------


def miscoverage_loss(
    cal_data: np.ndarray,
    lam: float,
) -> np.ndarray:
    """Compute per-sample miscoverage loss 1{|Yᵢ| > λ} for prediction intervals.

    Implements the 0-1 miscoverage loss for symmetric prediction intervals
    [-λ, λ] from Section 5.2 of the paper. The prediction interval fails to
    cover Yᵢ iff |Yᵢ| > λ.

    The loss is monotonically non-increasing in λ (larger interval → fewer
    misses → smaller loss), satisfying the CRC monotonicity assumption.

    Note: The X values in cal_data[:, 0] are not used in this loss — only
    the Y values in cal_data[:, 1] matter. X is stored in cal_data for
    consistency with the data generation interface.

    Args:
        cal_data: Calibration data of shape (n, 2) where column 0 contains
            X ~ Uniform[0, 4] and column 1 contains Y | X ~ N(0, X²).
            Generated by experiments/exp2_synthetic_heteroskedastic.
            generate_heteroskedastic_cal_data.
        lam: Half-width of the symmetric prediction interval [-λ, λ].
            Should be ≥ 0. The prediction interval covers Y iff |Y| ≤ λ.

    Returns:
        Binary array of shape (n,) with values in {0.0, 1.0}. Element i
        is 1.0 if Yᵢ is not covered by [-λ, λ], and 0.0 otherwise.

    Example:
        >>> cal_data = np.array([[1.0, 0.5], [2.0, -3.0], [3.0, 0.0]])
        >>> miscoverage_loss(cal_data, lam=1.0)
        array([0., 1., 0.])
        >>> miscoverage_loss(cal_data, lam=0.0)
        array([1., 1., 0.])
        >>> miscoverage_loss(cal_data, lam=np.inf)
        array([0., 0., 0.])
    """
    # Extract Y values from column 1. X values (column 0) are not used.
    # Shape: (n,)
    Y: np.ndarray = cal_data[:, 1]

    # Miscoverage: 1 if |Y| > λ, 0 otherwise.
    # Cast to float for compatibility with downstream arithmetic (e.g., mean).
    # Shape: (n,)
    losses: np.ndarray = (np.abs(Y) > lam).astype(float)
    return losses


def true_heteroskedastic_risk(
    lam: float,
    x_low: float = 0.0,
    x_high: float = 4.0,
    n_quad: int = 1000,
) -> float:
    """Compute the true miscoverage risk via numerical integration.

    Computes the true expected miscoverage probability for the heteroskedastic
    experiment (Section 5.2):

        R(θ, λ) = E_X[Pr(|Y| > λ | X)]
                = E_X[2 · Φ(−λ/X)]
                = ∫_{x_low}^{x_high} 2 · Φ(−λ/x) · (1/(x_high − x_low)) dx

    where X ~ Uniform[x_low, x_high] and Y | X ~ N(0, X²), so
    Pr(|Y| > λ | X) = Pr(|N(0, X²)| > λ) = 2 · Φ(−λ/X) by symmetry.

    A trial "fails" iff true_heteroskedastic_risk(λ_chosen) > α = 0.1
    (config.yaml: exp2_synthetic_heteroskedastic.alpha = 0.1).

    Numerical integration details:
        - Uses scipy.integrate.quad with adaptive quadrature.
        - The lower limit x_low = 0.0 creates a removable singularity at
          x = 0: as x → 0⁺, Φ(−λ/x) → 0 for λ > 0, so the integrand
          approaches 0. Integration starts from a small epsilon (1e-10)
          to avoid division by zero.
        - The n_quad parameter maps to the `limit` argument of quad,
          controlling the maximum number of adaptive subintervals.
          Per config.yaml: n_quad_true_risk = 1000.

    Special cases:
        - lam = 0.0: Φ(0) = 0.5, risk = 1.0 (complete miscoverage).
        - lam = np.inf: Φ(−∞) = 0, risk = 0.0 (perfect coverage).
        - lam < 0: Not expected; |Y| > λ is always True for λ < 0, risk = 1.0.

    Args:
        lam: Half-width of the symmetric prediction interval [-λ, λ].
            Should be ≥ 0 for meaningful results.
        x_low: Lower bound of X ~ Uniform[x_low, x_high]. Default 0.0 per
            config.yaml (exp2_synthetic_heteroskedastic.x_low = 0.0).
        x_high: Upper bound of X ~ Uniform[x_low, x_high]. Default 4.0 per
            config.yaml (exp2_synthetic_heteroskedastic.x_high = 4.0).
        n_quad: Maximum number of adaptive quadrature subintervals. Default
            1000 per config.yaml (exp2_synthetic_heteroskedastic.
            n_quad_true_risk = 1000). Passed as `limit` to scipy.integrate.quad.

    Returns:
        Scalar float in [0, 1] representing the true marginal miscoverage
        probability E_X[Pr(|Y| > λ | X)].

    Example:
        >>> # lam=0: complete miscoverage
        >>> abs(true_heteroskedastic_risk(0.0) - 1.0) < 1e-6
        True
        >>> # lam very large: near-zero miscoverage
        >>> true_heteroskedastic_risk(100.0) < 1e-4
        True
        >>> # lam=1.0: some miscoverage (exact value depends on X distribution)
        >>> 0.0 < true_heteroskedastic_risk(1.0) < 1.0
        True
    """
    # Handle special cases to avoid numerical issues.
    if lam == np.inf:
        return 0.0
    if lam <= 0.0:
        # For lam <= 0, |Y| > lam is always True (since |Y| >= 0 > lam for lam < 0,
        # and |Y| > 0 a.s. for continuous Y). Return 1.0.
        return 1.0

    # Width of the uniform distribution for normalization.
    width: float = x_high - x_low

    # Small epsilon to avoid division by zero at x = x_low = 0.
    # The integrand approaches 0 as x → 0⁺ (removable singularity), so
    # starting from epsilon instead of 0 introduces negligible error.
    integration_lower: float = max(x_low, 1e-10)

    def integrand(x: float) -> float:
        """Integrand: 2 · Φ(−λ/x) / (x_high − x_low)."""
        # norm.cdf(-lam / x) = Φ(−λ/x) = Pr(N(0,1) ≤ −λ/x)
        # = Pr(N(0, x²) ≥ λ) by scaling
        # Factor of 2 accounts for both tails: Pr(|N(0,x²)| > λ) = 2·Φ(−λ/x)
        return 2.0 * float(norm.cdf(-lam / x)) / width

    # Adaptive numerical integration using scipy.integrate.quad.
    # `limit` controls the maximum number of subintervals for adaptive refinement.
    # `epsabs` and `epsrel` are absolute and relative error tolerances.
    integral_value: float
    integral_value, _ = quad(
        integrand,
        integration_lower,
        x_high,
        limit=n_quad,
        epsabs=1.49e-8,
        epsrel=1.49e-8,
    )

    # Clamp to [0, 1] to handle any tiny numerical overshoot.
    return float(np.clip(integral_value, 0.0, 1.0))


# ---------------------------------------------------------------------------
# Experiment 3 — MS-COCO False Negative Rate (Section 5.3)
# ---------------------------------------------------------------------------


def fnr_loss(
    scores: np.ndarray,
    labels: np.ndarray,
    lam: float,
) -> np.ndarray:
    """Compute per-sample false negative rate (FNR) for multilabel classification.

    Implements the FNR loss for Experiment 3 (Section 5.3), mirroring the
    setup from Angelopoulos & Bates (2023, Section 5.1). The prediction set
    for sample i is:

        C_λ(xᵢ) = {c : score_ic ≥ λ}

    The per-sample FNR is:

        FNR_i = (# true labels not in prediction set) / (# true labels)
              = Σ_c [labels_ic · 1{score_ic < λ}] / Σ_c labels_ic

    IMPORTANT — direction of monotonicity:
        As λ increases, the prediction set shrinks (fewer labels included),
        so more true labels are excluded and FNR increases. This means FNR
        is monotonically NON-DECREASING in λ. The decision rules in
        decision_rules.py must account for this by searching the lambda_grid
        in the appropriate direction (finding the largest λ satisfying the
        risk criterion, not the smallest).

    Division by zero handling:
        Samples with no true labels (Σ_c labels_ic = 0) have undefined FNR.
        Per the design specification, these samples return FNR = 0.0.

    Args:
        scores: Softmax probability scores of shape (n, C) with values in
            [0, 1]. scores[i, c] is the predicted probability for class c
            on sample i. Loaded from config.yaml scores_path.
        labels: Binary ground-truth label matrix of shape (n, C) with values
            in {0, 1}. labels[i, c] = 1 iff class c is a true label for
            sample i. Loaded from config.yaml labels_path.
        lam: Score threshold λ ∈ [0, 1]. Labels with score ≥ λ are included
            in the prediction set. Higher λ → smaller prediction set → higher FNR.

    Returns:
        Array of shape (n,) with values in [0, 1]. Element i is the FNR
        for sample i: the fraction of true labels not included in the
        prediction set C_λ(xᵢ). Returns 0.0 for samples with no true labels.

    Example:
        >>> scores = np.array([[0.9, 0.3, 0.7], [0.5, 0.8, 0.2]])
        >>> labels = np.array([[1, 0, 1], [0, 1, 1]])
        >>> # lam=0.5: pred sets are {0,2} and {0,1}
        >>> # Sample 0: true={0,2}, pred={0,2}, FNR=0/2=0.0
        >>> # Sample 1: true={1,2}, pred={0,1}, FNR=1/2=0.5
        >>> fnr_loss(scores, labels, lam=0.5)
        array([0. , 0.5])
        >>> # lam=0.0: all labels included, FNR=0 for all
        >>> np.allclose(fnr_loss(scores, labels, lam=0.0), 0.0)
        True
        >>> # lam=1.0: no labels included, FNR=1 for all (with true labels)
        >>> fnr_loss(scores, labels, lam=1.0)
        array([1., 1.])
    """
    # Prediction set membership: C_λ(xᵢ) = {c : score_ic ≥ λ}.
    # Shape: (n, C), dtype bool
    in_pred_set: np.ndarray = scores >= lam

    # False negatives: true labels NOT in the prediction set.
    # labels_ic = 1 and score_ic < λ (i.e., not in pred set).
    # Shape: (n, C), dtype float
    false_negatives: np.ndarray = labels.astype(float) * (~in_pred_set).astype(float)

    # Count false negatives per sample: Σ_c [labels_ic · 1{score_ic < λ}].
    # Shape: (n,)
    fn_count: np.ndarray = np.sum(false_negatives, axis=1)

    # Count true labels per sample: Σ_c labels_ic.
    # Shape: (n,)
    true_count: np.ndarray = np.sum(labels.astype(float), axis=1)

    # Compute FNR with division-by-zero protection.
    # np.maximum(true_count, 1) prevents actual division by zero.
    # np.where masks out the result for samples with no true labels (→ 0.0).
    # Shape: (n,)
    fnr: np.ndarray = np.where(
        true_count > 0,
        fn_count / np.maximum(true_count, 1.0),
        0.0,
    )

    return fnr


def empirical_fnr_risk(
    scores: np.ndarray,
    labels: np.ndarray,
    lam: float,
) -> float:
    """Compute the empirical mean FNR on a dataset for a given threshold.

    Evaluates the average false negative rate across all samples in the
    provided dataset. Used to compute the true risk on the held-out test
    set in Experiment 3, determining whether a trial "fails" (risk > α).

    A trial fails iff empirical_fnr_risk(test_scores, test_labels, λ) > α
    where α = 0.1 per config.yaml (exp3_mscoco.alpha = 0.1).

    Args:
        scores: Softmax scores of shape (n, C) with values in [0, 1].
            Should be the TEST set scores (not calibration) for risk evaluation.
        labels: Binary ground-truth labels of shape (n, C) with values in {0, 1}.
            Should be the TEST set labels.
        lam: Score threshold λ ∈ [0, 1] chosen by the decision rule.

    Returns:
        Scalar float in [0, 1] equal to the mean FNR across all n samples:
        (1/n) · Σᵢ FNR_i.

    Example:
        >>> scores = np.array([[0.9, 0.3, 0.7], [0.5, 0.8, 0.2]])
        >>> labels = np.array([[1, 0, 1], [0, 1, 1]])
        >>> empirical_fnr_risk(scores, labels, lam=0.5)
        0.25
        >>> empirical_fnr_risk(scores, labels, lam=0.0)
        0.0
    """
    per_sample_fnr: np.ndarray = fnr_loss(scores, labels, lam)
    return float(np.mean(per_sample_fnr))


def pred_set_size(
    scores: np.ndarray,
    lam: float,
) -> float:
    """Compute the mean prediction set size for a given score threshold.

    The prediction set for sample i is C_λ(xᵢ) = {c : score_ic ≥ λ}.
    This function returns the average number of labels included across all
    samples. Used to compute the "Pred. Set Size" column in Table 3.

    Note: This is typically evaluated on the test set (not calibration set)
    to report the expected prediction set size at deployment.

    Relationship to λ: As λ increases, fewer labels meet the threshold,
    so the mean prediction set size decreases. The goal is to find the
    largest λ (smallest prediction set) that still controls the FNR risk.

    Args:
        scores: Softmax scores of shape (n, C) with values in [0, 1].
            Typically the test set scores.
        lam: Score threshold λ ∈ [0, 1]. Labels with score ≥ λ are included.

    Returns:
        Scalar float ≥ 0 equal to the mean number of labels in the prediction
        set: (1/n) · Σᵢ |C_λ(xᵢ)|. Ranges from 0 (no labels included at
        lam > max score) to C (all labels included at lam = 0).

    Example:
        >>> scores = np.array([[0.9, 0.3, 0.7], [0.5, 0.8, 0.2]])
        >>> pred_set_size(scores, lam=0.5)  # {0,2} and {0,1} → sizes 2,2 → mean 2.0
        2.0
        >>> pred_set_size(scores, lam=0.0)  # All 3 labels included for both → 3.0
        3.0
        >>> pred_set_size(scores, lam=1.0)  # No labels included → 0.0
        0.0
    """
    # Count labels in prediction set per sample: |{c : score_ic ≥ λ}|.
    # Shape: (n,), dtype int
    set_sizes: np.ndarray = np.sum(scores >= lam, axis=1)

    # Return mean set size across all samples.
    return float(np.mean(set_sizes))
