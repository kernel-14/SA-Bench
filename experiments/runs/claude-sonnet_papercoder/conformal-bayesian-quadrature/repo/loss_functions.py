## loss_functions.py
"""Loss functions and true risk computations for all three experiments.

This module is a pure utility layer — no classes, no state, no side effects.
Every function takes NumPy arrays and scalars and returns NumPy arrays or
scalars. It sits at the bottom of the dependency graph with no project-internal
imports.

Functions provided:

  Experiment 1 — Synthetic Binomial (Section 5.1):
    binomial_loss          : per-sample ℓ(zᵢ, λ) = (1/K) Σₖ 1{Vᵢₖ > λ}
    true_binomial_risk     : analytical E[ℓ] = 1 − λ

  Experiment 2 — Synthetic Heteroskedastic (Section 5.2):
    miscoverage_loss       : per-sample 1{|Yᵢ| > λ}
    true_heteroskedastic_risk : E_X[2Φ(−λ/X)] via numerical integration

  Experiment 3 — MS-COCO FNR (Section 5.3):
    fnr_loss               : per-sample false negative rate
    empirical_fnr_risk     : mean FNR on a test set
    pred_set_size          : mean prediction set size for a score threshold

References:
    Paper Section 5.1: binomial loss, true risk = 1 − λ.
    Paper Section 5.2: miscoverage loss, heteroskedastic true risk.
    Paper Section 5.3: FNR loss, mirrors Angelopoulos & Bates (2023) §5.1.
    config.yaml: exp1_synthetic_binomial.K=4, exp2_synthetic_heteroskedastic.
        x_low=0.0, x_high=4.0, n_quad_true_risk=1000, exp3_mscoco.alpha=0.1.
"""

import numpy as np
from scipy.integrate import quad
from scipy.stats import norm


# ---------------------------------------------------------------------------
# Experiment 1 — Synthetic Binomial Data (Section 5.1)
# ---------------------------------------------------------------------------


def binomial_loss(
    cal_data: np.ndarray,
    lam: float,
    K: int = 4,
) -> np.ndarray:
    """Compute per-sample binomial loss ℓ(zᵢ, λ) = (1/K) Σₖ 1{Vᵢₖ > λ}.

    Implements the loss from Section 5.1 of the paper:

        ℓ(zᵢ, λ) = (1/K) · Σₖ₌₁ᴷ 1{Vᵢₖ > λ}

    where Vᵢₖ ~ Uniform(0, 1). The result is a scaled binomial proportion
    in {0, 1/K, 2/K, ..., 1}. The loss is monotonically non-increasing in
    λ (larger λ → fewer Vᵢₖ exceed the threshold → smaller loss), satisfying
    the CRC monotonicity assumption (Proposition 3.2).

    The true expected loss is E[ℓ(z, λ)] = 1 − λ (see true_binomial_risk).
    Risk exceeds α = 0.4 iff λ < 0.6 (config.yaml: risk_threshold = 0.6).

    Args:
        cal_data: Calibration data matrix of shape (n, K) where each entry
            Vᵢₖ is drawn from Uniform(0, 1). Generated by
            experiments/exp1_synthetic_binomial.generate_binomial_cal_data.
        lam: Threshold parameter λ ∈ [0, 1]. The loss counts the fraction
            of the K uniform samples that exceed this threshold.
        K: Binomial averaging parameter. Must match the number of columns
            in cal_data. Default 4 per config.yaml
            (exp1_synthetic_binomial.K = 4).

    Returns:
        Array of shape (n,) with values in {0, 1/K, 2/K, ..., 1}.
        Element i is the fraction of the K uniform samples for observation i
        that exceed λ.

    Example:
        >>> rng = np.random.default_rng(42)
        >>> cal_data = rng.uniform(0, 1, size=(5, 4))
        >>> losses = binomial_loss(cal_data, lam=0.6, K=4)
        >>> losses.shape
        (5,)
        >>> np.all((losses >= 0) & (losses <= 1))
        True
        >>> # At lam=0, all entries exceed threshold → loss = 1.0 for all
        >>> np.allclose(binomial_loss(cal_data, lam=0.0, K=4), 1.0)
        True
        >>> # At lam=1, no entries exceed threshold → loss = 0.0 for all
        >>> np.allclose(binomial_loss(cal_data, lam=1.0, K=4), 0.0)
        True
    """
    # np.mean along axis=1 computes (1/K) * Σₖ 1{Vᵢₖ > λ} for each row i.
    # This is equivalent to explicit division by K but avoids integer overflow
    # and is more numerically clean.
    # Shape: (n,)
    losses: np.ndarray = np.mean(cal_data > lam, axis=1).astype(float)
    return losses


def true_binomial_risk(lam: float) -> float:
    """Compute the analytical true expected loss for the binomial experiment.

    From Section 5.1 of the paper: "Since the expectation of the loss (34)
    is 1 − λ, any trial for which λ < 0.6 constitutes a risk exceeding the
    α threshold."

    Derivation:
        E[ℓ(z, λ)] = E[(1/K) · Σₖ 1{Vᵢₖ > λ}]
                    = Pr(V > λ)          (linearity of expectation, V ~ U(0,1))
                    = 1 − λ

    This is purely analytical — no calibration data is needed. A trial
    "fails" (risk exceeds α = 0.4) iff true_binomial_risk(λ_chosen) > 0.4,
    i.e., λ_chosen < 0.6 (config.yaml: risk_threshold = 0.6).

    Special cases:
        - lam = np.inf: returns −∞, which is ≤ α, so no failure. Correct
          because λ = ∞ means the prediction set covers everything (zero risk).
        - lam = 0.0: returns 1.0 (maximum risk).
        - lam = 1.0: returns 0.0 (zero risk).

    Args:
        lam: The decision rule threshold λ chosen by a method. Typically
            in [0, 1] for this experiment, but np.inf is valid (returned
            when no λ in the grid satisfies the criterion).

    Returns:
        Scalar float equal to 1.0 − lam. Values in (−∞, 1.0].

    Example:
        >>> true_binomial_risk(0.6)
        0.4
        >>> true_binomial_risk(0.7)
        0.30000000000000004
        >>> true_binomial_risk(0.0)
        1.0
        >>> true_binomial_risk(1.0)
        0.0
        >>> true_binomial_risk(np.inf)  # No failure: -inf <= alpha
        -inf
    """
    return 1.0 - lam


