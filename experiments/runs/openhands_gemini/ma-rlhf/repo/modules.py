
import torch
from typing import List, Tuple, Optional
import numpy as np
from transformers import PreTrainedTokenizer

from config import MAConfig

class MacroActionModule:
    """
    Implements the macro action logic for MA-RLHF, including termination conditions
    and value estimation.
    """
    def __init__(self, ma_config: MAConfig, tokenizer: PreTrainedTokenizer):
        self.ma_config = ma_config
        self.tokenizer = tokenizer

    def get_macro_action_positions(
        self,
        start_idx: int,
        attention_mask: torch.Tensor,
        generated_tokens: List[int], # Full sequence of generated tokens (input_ids)
        ppl_scores: Optional[torch.Tensor] = None, # Perplexity scores for the sequence
    ) -> List[int]:
        """
        Obtains the starting positions of macro actions based on the specified termination rule.
        Corresponds to `get_macro_action_positions` in Appendix E.

        Args:
            start_idx: The starting index of the generated sequence (i.e., prompt length).
            attention_mask: Attention mask for the full sequence.
            generated_tokens: List of token IDs generated by the policy.
            ppl_scores: Perplexity scores for each token in the sequence.

        Returns:
            A list of indices representing the start of each macro action.
        """
        sequence_indices = list(range(start_idx, attention_mask.size(1)))
        
        # Original sequence for macro action calculation starts from `start_idx`
        # and excludes any padding or future tokens
        actual_generated_len = (attention_mask[0, start_idx:] == 1).sum().item()
        
        macro_action_starts = [start_idx]
        current_macro_start = start_idx

        if self.ma_config.termination_condition == "fixed_ngram":
            n_gram = self.ma_config.n_gram
            if n_gram is None:
                raise ValueError("n_gram must be specified for fixed_ngram termination.")
            
            current_count = 0
            for i in range(actual_generated_len):
                current_count += 1 # Each token contributes 1 to the count
                if current_count == n_gram:
                    macro_action_starts.append(current_macro_start + i + 1)
                    current_macro_start += i + 1
                    current_count = 0
            
            # Ensure the last macro action is always included, even if shorter than n_gram
            if current_macro_start < start_idx + actual_generated_len and macro_action_starts[-1] != start_idx + actual_generated_len:
                # If the last segment is not n_gram long, it still forms a macro action
                pass # Already handled by adding start_idx + i + 1 implicitly


        elif self.ma_config.termination_condition == "randomized_ngram":
            k_list = torch.tensor(self.ma_config.randomized_ngram_lengths, dtype=torch.int)
            k_list = k_list.repeat(3) # Repeat 3 times as per paper (Appendix B.4)
            k_list = k_list[torch.randperm(k_list.size(0))] # Shuffle
            
            current_pos = start_idx
            for k in k_list:
                if current_pos + k > start_idx + actual_generated_len:
                    break
                macro_action_starts.append(current_pos + k)
                current_pos += k
            
            # Add the last segment if any tokens remain
            if current_pos < start_idx + actual_generated_len and macro_action_starts[-1] != start_idx + actual_generated_len:
                macro_action_starts.append(start_idx + actual_generated_len)

        elif self.ma_config.termination_condition == "perplexity":
            if ppl_scores is None:
                raise ValueError("Perplexity scores must be provided for perplexity-based termination.")
            
            # ppl_scores should correspond to the generated_tokens starting from start_idx
            # The paper states: "Mathematically, it can be represented as ωτ = {atτ , atτ +1 , . . . , atτ +|ωτ |−1 } 
            # where Ptτ = {ptτ , ptτ +1 , . . . , ptτ +|ωτ |−1 } exhibits a monotonic decreasing pattern."
            
            # This implementation assumes ppl_scores is the negative log-likelihood for each token
            # (lower is better, so we look for monotonic decreasing patterns in the scores)
            # The paper's definition of ppl(ωτ) ∝ − 1/|ωτ| Σa∈ωτ Pa means lower average entropy is better.
            # And "A macro action terminates until it reaches a token that has negative impact on the perplexity of the macro action."
            # This suggests that we keep extending the macro action as long as adding the next token
            # *decreases* (or maintains a decreasing trend in) the perplexity of the current macro action.
            # If `ppl[i] > ppl[i-1]` signifies an increase in perplexity, then we terminate.
            
            # Adjust ppl_scores to match the generated sequence length
            ppl_scores_segment = ppl_scores[start_idx : start_idx + actual_generated_len]

            for i in range(1, actual_generated_len):
                # The condition `ppl[i] > ppl[i-1]` is what triggers a termination
                # based on the pseudocode in Appendix E.
                # Assuming ppl_scores here are token-level perplexities/negative log-likelihoods.
                if ppl_scores_segment[i] > ppl_scores_segment[i-1]:
                    macro_action_starts.append(start_idx + i)
            
            # Ensure the last macro action end is included if it hasn't been terminated yet
            if macro_action_starts[-1] != start_idx + actual_generated_len:
                macro_action_starts.append(start_idx + actual_generated_len)

        elif self.ma_config.termination_condition == "parsing":
            # This is a placeholder. Full implementation requires a parsing library.
            # The paper describes:
            # 1. Traverse constituent tree using DFS.
            # 2. Expand nonterminal nodes until current non-terminal state contains no more than C leaf tokens.
            # 3. Rules: (1) nodes with < C tokens mark end; (2) single-token nodes included in last MA.
            # 4. Due to tokenizer differences, revert to standard PPO when discrepancies occur.
            # This implies needing to parse `generated_tokens` into a tree structure.
            # For reproduction, we'll need to mock this or assume it's external.
            # For now, let's fall back to fixed_ngram (n=5) as a proxy.
            print("WARNING: Parsing-based termination is a placeholder and falls back to fixed_ngram (n=5).")
            n_gram = self.ma_config.parsing_cutoff # Use cutoff as n-gram length for placeholder
            if n_gram is None: n_gram = 5 # default if cutoff is not set
            
            current_count = 0
            for i in range(actual_generated_len):
                current_count += 1
                if current_count == n_gram:
                    macro_action_starts.append(current_macro_start + i + 1)
                    current_macro_start += i + 1
                    current_count = 0
            
            if current_macro_start < start_idx + actual_generated_len and macro_action_starts[-1] != start_idx + actual_generated_len:
                pass

        else:
            raise ValueError(f"Unknown termination condition: {self.ma_config.termination_condition}")

        # The last element in macro_action_starts should be the end of the sequence
        # We need the split points, so if the last element is the total length, keep it.
        # Otherwise, add the end of the sequence to ensure all tokens are covered.
        if not macro_action_starts or macro_action_starts[-1] < start_idx + actual_generated_len:
             macro_action_starts.append(start_idx + actual_generated_len)
        
        # Filter out consecutive identical indices (can happen if start_idx is already the end)
        unique_macro_action_starts = [macro_action_starts[0]]
        for i in range(1, len(macro_action_starts)):
            if macro_action_starts[i] > unique_macro_action_starts[-1]:
                unique_macro_action_starts.append(macro_action_starts[i])
        
        return unique_macro_action_starts


    def get_macro_action_values(
        self,
        token_values: torch.Tensor, # (batch_size, sequence_length, 1)
        attention_mask: torch.Tensor, # (batch_size, sequence_length)
        start_idx: int, # start of generated tokens
        macro_action_positions: List[int],
    ) -> torch.Tensor:
        """
        Calculates the value for each macro action.
        Corresponds to `get_macro_action_values` in Appendix E.

        Args:
            token_values: Value estimates for each token.
            attention_mask: Attention mask for the full sequence.
            start_idx: The starting index of the generated sequence (i.e., prompt length).
            macro_action_positions: List of indices indicating the start of each macro action.

        Returns:
            A tensor of macro action values (batch_size, num_macro_actions).
        """
        batch_size = token_values.size(0)
        
        # Ensure macro_action_positions are relative to the start of the sequence
        # and include the end point.
        if macro_action_positions[0] != start_idx:
            # This should ideally not happen if get_macro_action_positions is called correctly
            # or macro_action_positions is already adjusted.
            # For safety, let's adjust here if it's based on absolute indices from the start of padded sequence.
            adjusted_ma_positions = [pos - start_idx for pos in macro_action_positions if pos >= start_idx]
            if 0 not in adjusted_ma_positions:
                adjusted_ma_positions.insert(0, 0)
        else:
            adjusted_ma_positions = [pos - start_idx for pos in macro_action_positions]

        # The split list should represent the lengths of each macro action segment.
        # It's the difference between consecutive macro action start positions.
        # If `macro_action_positions` is `[p_0, p_1, ..., p_k]` where `p_0` is `start_idx`
        # and `p_k` is the end of the generated sequence.
        # Then the lengths are `p_1 - p_0`, `p_2 - p_1`, ...
        split_lengths = [adjusted_ma_positions[i+1] - adjusted_ma_positions[i] for i in range(len(adjusted_ma_positions) - 1)]

        if not split_lengths: # No generated tokens or only prompt
            return torch.zeros(batch_size, 0, dtype=token_values.dtype, device=token_values.device)

        # Extract the token values and mask relevant to the generated part of the sequence
        generated_token_values = token_values[:, start_idx:]
        generated_attention_mask = attention_mask[:, start_idx:]

        macro_action_values = torch.zeros(batch_size, len(split_lengths), dtype=token_values.dtype, device=token_values.device)

        for b in range(batch_size):
            # Split the values and mask for the current batch item
            current_generated_values = generated_token_values[b, : (generated_attention_mask[b] == 1).sum().item()]
            current_generated_mask = generated_attention_mask[b, : (generated_attention_mask[b] == 1).sum().item()]
            
            # Handle cases where current_generated_values might be empty or shorter than expected.
            if current_generated_values.numel() == 0:
                 continue

            # Need to adjust split_lengths if the actual generated length is shorter than the planned splits
            current_split_lengths = []
            cumulative_len = 0
            for length in split_lengths:
                if cumulative_len + length <= current_generated_values.size(0):
                    current_split_lengths.append(length)
                    cumulative_len += length
                else:
                    # If remaining part is non-empty, add it as the last segment
                    if current_generated_values.size(0) - cumulative_len > 0:
                        current_split_lengths.append(current_generated_values.size(0) - cumulative_len)
                    break
            
            # If no splits were determined (e.g., if generated length is 0), skip.
            if not current_split_lengths:
                continue

            # This splts the sequence of token values into macro action segments
            splited_values = torch.split(current_generated_values.squeeze(-1), current_split_lengths)
            splited_mask = torch.split(current_generated_mask, current_split_lengths)

            for idx, (value_i, mask_i) in enumerate(zip(splited_values, splited_mask)):
                # Apply value estimation assignment logic
                if self.ma_config.value_estimation_assignment == "equal":
                    # Paper's pseudocode takes mean of masked values
                    masked_values = value_i[mask_i == 1]
                    if masked_values.numel() > 0:
                        macro_action_values[b, idx] = torch.mean(masked_values)
                    else:
                        macro_action_values[b, idx] = 0.0 # Or some default value
                elif self.ma_config.value_estimation_assignment == "unit":
                    # "use the value function of the last action as the macro action’s value function"
                    masked_values = value_i[mask_i == 1]
                    if masked_values.numel() > 0:
                        macro_action_values[b, idx] = masked_values[-1]
                    else:
                        macro_action_values[b, idx] = 0.0
                elif self.ma_config.value_estimation_assignment == "position_decayed":
                    # "contributions of each value function of tokens are determined by taking the position into consideration."
                    # sigma_tau = { 1 / (|omega_tau| - i) * H } where H = sum(1 / (|omega_tau| - i))
                    masked_values = value_i[mask_i == 1]
                    if masked_values.numel() > 0:
                        omega_tau_len = masked_values.numel()
                        if omega_tau_len == 0:
                            macro_action_values[b, idx] = 0.0
                            continue
                        
                        # Calculate H
                        h_sum = 0.0
                        for i_pos in range(omega_tau_len):
                            h_sum += 1.0 / (omega_tau_len - i_pos)
                        
                        # Calculate sigma_tau for each token in the macro action
                        sigma_tau_weights = torch.tensor([1.0 / ((omega_tau_len - i_pos) * h_sum) for i_pos in range(omega_tau_len)], 
                                                        dtype=masked_values.dtype, device=masked_values.device)
                        
                        macro_action_values[b, idx] = torch.sum(masked_values * sigma_tau_weights)
                    else:
                        macro_action_values[b, idx] = 0.0
                else:
                    raise ValueError(f"Unknown value estimation assignment: {self.ma_config.value_estimation_assignment}")
        
        return macro_action_values

    def policy_loss_macro_action(
        self,
        logprobs: torch.Tensor, # (batch_size, sequence_length)
        old_logprobs: torch.Tensor, # (batch_size, sequence_length)
        advantages: torch.Tensor, # (batch_size, num_macro_actions) - these are macro advantages
        attention_mask: torch.Tensor, # (batch_size, sequence_length)
        macro_action_positions: List[int],
        clip_ratio: float,
        start_idx: int, # start of generated tokens
    ) -> torch.Tensor:
        """
        Calculates the PPO policy loss adapted for macro actions.
        Corresponds to `policy_loss_macro_action` in Appendix E.
        """
        batch_size, sequence_length = logprobs.size()
        
        # Ensure macro_action_positions are relative to the start of the sequence
        adjusted_ma_positions = [pos - start_idx for pos in macro_action_positions if pos >= start_idx]
        if 0 not in adjusted_ma_positions:
            adjusted_ma_positions.insert(0, 0)
        
        split_lengths = [adjusted_ma_positions[i+1] - adjusted_ma_positions[i] for i in range(len(adjusted_ma_positions) - 1)]

        if not split_lengths:
            return torch.tensor(0.0, device=logprobs.device) # No generated tokens, no loss

        # Only consider logprobs/old_logprobs for the generated part
        generated_logprobs = logprobs[:, start_idx:]
        generated_old_logprobs = old_logprobs[:, start_idx:]
        generated_attention_mask = attention_mask[:, start_idx:]

        pg_loss = 0.0
        total_mask_sum = torch.tensor(0.0, device=logprobs.device)

        for b in range(batch_size):
            current_logprobs = generated_logprobs[b, : (generated_attention_mask[b] == 1).sum().item()]
            current_old_logprobs = generated_old_logprobs[b, : (generated_attention_mask[b] == 1).sum().item()]
            current_mask = generated_attention_mask[b, : (generated_attention_mask[b] == 1).sum().item()]
            current_advantages = advantages[b] # (num_macro_actions,)

            if current_logprobs.numel() == 0:
                continue

            current_split_lengths = []
            cumulative_len = 0
            for length in split_lengths:
                if cumulative_len + length <= current_logprobs.size(0):
                    current_split_lengths.append(length)
                    cumulative_len += length
                else:
                    if current_logprobs.size(0) - cumulative_len > 0:
                        current_split_lengths.append(current_logprobs.size(0) - cumulative_len)
                    break
            
            if not current_split_lengths:
                continue

            splited_logprobs = torch.split(current_logprobs, current_split_lengths)
            splited_old_logprobs = torch.split(current_old_logprobs, current_split_lengths)
            splited_mask = torch.split(current_mask, current_split_lengths)

            for i in range(len(current_split_lengths)):
                log_ratio_i = (splited_logprobs[i] - splited_old_logprobs[i]) * splited_mask[i]
                ratio_i = torch.exp(log_ratio_i)
                
                # Advantages are per macro action
                advantage_i = current_advantages[i]

                pg_loss1 = -advantage_i * ratio_i
                pg_loss2 = -advantage_i * torch.clamp(ratio_i, 1.0 - clip_ratio, 1.0 + clip_ratio)
                
                # Sum over tokens within the macro action, then add to total pg_loss
                pg_loss += torch.sum(torch.max(pg_loss1, pg_loss2)) # The pseudocode has *mask_i here, but given that log_ratio_i was already *mask_i
                                                                       # and pg_loss1/2 are element-wise, summing should be correct for unmasked elements
                total_mask_sum += splited_mask[i].sum()
        
        if total_mask_sum > 0:
            return pg_loss / total_mask_sum
        else:
            return torch.tensor(0.0, device=logprobs.device)


    def critic_loss_macro_action(
        self,
        values: torch.Tensor, # (batch_size, sequence_length, 1)
        old_values: torch.Tensor, # (batch_size, sequence_length, 1)
        returns: torch.Tensor, # (batch_size, num_macro_actions) - these are macro returns
        attention_mask: torch.Tensor, # (batch_size, sequence_length)
        macro_action_positions: List[int],
        clip_ratio: float,
        start_idx: int, # start of generated tokens
    ) -> torch.Tensor:
        """
        Calculates the PPO critic (value function) loss adapted for macro actions.
        Corresponds to `critic_loss_macro_action` in Appendix E.
        """
        batch_size, sequence_length, _ = values.size()
        
        # Ensure macro_action_positions are relative to the start of the sequence
        adjusted_ma_positions = [pos - start_idx for pos in macro_action_positions if pos >= start_idx]
        if 0 not in adjusted_ma_positions:
            adjusted_ma_positions.insert(0, 0)
        
        split_lengths = [adjusted_ma_positions[i+1] - adjusted_ma_positions[i] for i in range(len(adjusted_ma_positions) - 1)]

        if not split_lengths:
            return torch.tensor(0.0, device=values.device) # No generated tokens, no loss

        # Only consider values/old_values for the generated part
        generated_values = values[:, start_idx:]
        generated_old_values = old_values[:, start_idx:]
        generated_attention_mask = attention_mask[:, start_idx:]

        vf_loss = 0.0
        total_mask_sum = torch.tensor(0.0, device=values.device)

        for b in range(batch_size):
            current_values = generated_values[b, : (generated_attention_mask[b] == 1).sum().item()]
            current_old_values = generated_old_values[b, : (generated_attention_mask[b] == 1).sum().item()]
            current_mask = generated_attention_mask[b, : (generated_attention_mask[b] == 1).sum().item()]
            current_returns = returns[b] # (num_macro_actions,)

            if current_values.numel() == 0:
                continue
            
            current_split_lengths = []
            cumulative_len = 0
            for length in split_lengths:
                if cumulative_len + length <= current_values.size(0):
                    current_split_lengths.append(length)
                    cumulative_len += length
                else:
                    if current_values.size(0) - cumulative_len > 0:
                        current_split_lengths.append(current_values.size(0) - cumulative_len)
                    break
            
            if not current_split_lengths:
                continue

            splited_values = torch.split(current_values.squeeze(-1), current_split_lengths)
            splited_old_values = torch.split(current_old_values.squeeze(-1), current_split_lengths)
            splited_mask = torch.split(current_mask, current_split_lengths)

            for i in range(len(current_split_lengths)):
                value_i = splited_values[i]
                old_value_i = splited_old_values[i]
                mask_i = splited_mask[i]
                
                return_i = current_returns[i] # Target for this macro action

                # Clipped value objective
                vpred_clipped = old_value_i + torch.clamp(value_i - old_value_i, -clip_ratio, clip_ratio)
                
                # Equation for value loss usually includes 0.5 * MSE
                vf_loss1 = (value_i - return_i).pow(2)
                vf_loss2 = (vpred_clipped - return_i).pow(2)
                
                vf_loss += torch.sum(0.5 * torch.max(vf_loss1, vf_loss2) * mask_i)
                total_mask_sum += mask_i.sum()
        
        if total_mask_sum > 0:
            return vf_loss / total_mask_sum
        else:
            return torch.tensor(0.0, device=values.device)


    def get_advantages_and_returns(
        self,
        macro_action_values: torch.Tensor, # (batch_size, num_macro_actions)
        macro_action_rewards: torch.Tensor, # (batch_size, num_macro_actions)
        gamma: float, # Discount factor (paper states gamma=1 for GAE)
        lam: float, # Lambda for GAE
    ) -> Tuple[torch.Tensor, torch.Tensor]:
        """
        Calculates advantages and returns for macro actions using Generalized Advantage Estimation (GAE).
        The paper mentions "apply Generalized Advantage Estimation (GAE) without modification to derive
        advantage estimates and state-action value functions."
        """
        batch_size, num_macro_actions = macro_action_values.size()
        advantages = torch.zeros_like(macro_action_rewards)
        returns = torch.zeros_like(macro_action_rewards)

        for b in range(batch_size):
            last_gae_lam = 0
            for t in reversed(range(num_macro_actions)):
                if t == num_macro_actions - 1:
                    next_value = 0 # End of trajectory, no next state value
                else:
                    next_value = macro_action_values[b, t + 1]
                
                delta = macro_action_rewards[b, t] + gamma * next_value - macro_action_values[b, t]
                advantages[b, t] = last_gae_lam = delta + gamma * lam * last_gae_lam
            returns[b] = advantages[b] + macro_action_values[b]
            
        return advantages, returns

